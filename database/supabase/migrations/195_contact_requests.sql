-- Migration 195: Contact request intake (public contact form + ticketing)
--
-- PURPOSE
--   Backs the public "Contact us" form on the marketing site. Every submission
--   becomes a row here and is answered against a human ticket reference
--   (LB-YYMM-NNNNNN) that the submitter is shown and emailed.
--
-- WHY THIS TABLE IS NOT TENANT-SCOPED
--   Every commerce table in this schema carries site_id and is isolated by RLS
--   on it. This one cannot: most submitters have no account, no session and no
--   store. Even the ones who do (relationship = 'merchant') are identified only
--   by a self-declared subdomain we have not verified — trusting that string
--   enough to hang site_id off it would invent a tenant link that does not
--   exist. It is therefore a PLATFORM table: written only by the gateway
--   (service_role), readable only by service_role. No anon or authenticated
--   role gets any access at all, which is stricter than tenant tables.
--
-- RELATIONSHIP TO demo_requests (194)
--   Deliberately separate. A demo request is one shape of one question with a
--   scheduling slot and a one-open-per-email rule. A contact request is any of
--   thirteen topics, has no slot, and the SAME person may legitimately open
--   several at once (a payout query and a GST query are not duplicates). Fusing
--   them would mean a nullable half-table and a dedup rule that is wrong for
--   one of the two.
--
-- PII
--   Name, email, phone, company, city and GSTIN are personal data under the
--   DPDP Act. The lawful basis is the person's own request for contact.
--   consent_privacy is stored as an explicit act, not assumed. Retention is
--   operator-driven: status + resolved_at are what a purge job prunes against.
--
-- ABUSE
--   A public unauthenticated write is a spam target. Mitigations are layered:
--     • Turnstile verified at the gateway before anything touches this table
--     • client_token UNIQUE, so a double-click or a retry returns the first
--       ticket rather than opening a second one — enforced by the index, so
--       two simultaneous posts cannot both win
--     • ip_hash stored (hashed, never raw) so an operator can rate-limit a
--       source without holding a raw address against a named person
--     • the gateway throttles per email/IP against recent rows here

CREATE TABLE IF NOT EXISTS public.contact_requests (
    id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),

    -- The reference a human quotes. Generated by a DEFAULT (see below) so it is
    -- assigned inside the INSERT and can never be null or duplicated.
    ticket_ref             text        NOT NULL UNIQUE,

    -- Who
    full_name              text        NOT NULL,
    email                  text        NOT NULL,
    phone                  text        NOT NULL,
    phone_country_code     text,
    relationship           text        NOT NULL DEFAULT 'prospect',
    company_name           text,
    website_url            text,
    -- Self-declared, NOT verified. Never join tenant data on this.
    store_subdomain        text,
    gstin                  text,
    city                   text,
    state                  text,

    -- Their business, when the topic asks for it
    business_type          text,
    current_channel        text,
    monthly_orders         text,
    monthly_gmv_band       text,
    interested_plan        text,
    timeline               text,

    -- What they are asking
    topic                  text        NOT NULL,
    subject_id             text        NOT NULL,
    -- Their own words, when the catalog subject was not close enough.
    subject_text           text,
    subject_line           text        NOT NULL,
    message                text        NOT NULL,
    urgency                text        NOT NULL DEFAULT 'normal',
    order_reference        text,

    -- How they want the answer
    preferred_channel      text        NOT NULL DEFAULT 'email',
    preferred_language     text        NOT NULL DEFAULT 'en',
    preferred_time_window  text        NOT NULL DEFAULT 'any',

    -- Consent, recorded as an act rather than assumed
    consent_privacy        boolean     NOT NULL DEFAULT false,
    consent_marketing      boolean     NOT NULL DEFAULT false,

    -- Triage. Computed at the gateway from transparent arithmetic so an
    -- operator can argue with the number rather than trust it.
    team                   text        NOT NULL DEFAULT 'support',
    lead_score             integer     NOT NULL DEFAULT 0,
    lead_band              text        NOT NULL DEFAULT 'standard',
    -- The promise we made in the confirmation email. Stored, not recomputed,
    -- because the catalog may change after the promise was sent.
    response_hours         integer     NOT NULL DEFAULT 24,
    first_response_due_at  timestamptz,

    -- Operator workflow
    status                 text        NOT NULL DEFAULT 'new',
    assigned_to            text,
    responded_at           timestamptz,
    resolved_at            timestamptz,
    internal_notes         text,

    -- Provenance
    heard_about_us         text,
    locale                 text,
    source_path            text,
    referrer               text,
    utm                    jsonb       NOT NULL DEFAULT '{}'::jsonb,
    ip_hash                text,
    user_agent             text,
    -- Client-generated idempotency key. UNIQUE below.
    client_token           text        NOT NULL,

    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT contact_requests_status_check
        CHECK (status IN ('new', 'triaged', 'in_progress', 'waiting_on_customer', 'resolved', 'closed', 'spam')),
    CONSTRAINT contact_requests_urgency_check
        CHECK (urgency IN ('low', 'normal', 'high', 'critical')),
    CONSTRAINT contact_requests_channel_check
        CHECK (preferred_channel IN ('email', 'phone', 'whatsapp')),
    CONSTRAINT contact_requests_lead_band_check
        CHECK (lead_band IN ('hot', 'warm', 'standard')),
    CONSTRAINT contact_requests_lead_score_range_check
        CHECK (lead_score BETWEEN 0 AND 100),
    CONSTRAINT contact_requests_response_hours_check
        CHECK (response_hours BETWEEN 1 AND 720),
    -- Cheap structural guards. Real validation happens at the gateway against
    -- the shared catalog; these exist so a bad direct write cannot land rubbish.
    CONSTRAINT contact_requests_email_shape_check
        CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT contact_requests_full_name_present_check
        CHECK (length(btrim(full_name)) > 0),
    CONSTRAINT contact_requests_phone_present_check
        CHECK (length(btrim(phone)) > 0),
    -- Presence only, NOT the product's 20-character minimum. Postgres length()
    -- counts code points; the gateway's Zod .min() counts UTF-16 units. A
    -- message ending in an emoji is 20 to the gateway and 19 here, so a
    -- >= 20 CHECK would reject input the gateway had already accepted — and
    -- the sender would lose the message to a constraint they cannot see. The
    -- length rule belongs to the layer that can explain itself.
    CONSTRAINT contact_requests_message_present_check
        CHECK (length(btrim(message)) > 0),
    CONSTRAINT contact_requests_ticket_ref_shape_check
        CHECK (ticket_ref ~ '^LB-[0-9]{4}-[0-9]{6}$')
);

COMMENT ON TABLE public.contact_requests IS
    'Public contact-form submissions. Pre-tenant: no site_id exists for most submitters. Platform-scoped, service_role only.';
COMMENT ON COLUMN public.contact_requests.ticket_ref IS
    'Human reference quoted by the submitter and printed in both emails. Format LB-YYMM-NNNNNN, assigned by DEFAULT.';
COMMENT ON COLUMN public.contact_requests.store_subdomain IS
    'Self-declared and UNVERIFIED. Never treat as a tenant link — no RLS or join may depend on it.';
COMMENT ON COLUMN public.contact_requests.ip_hash IS
    'Salted hash of the submitter IP. Never store the raw address — it is personal data with no operational need here.';
COMMENT ON COLUMN public.contact_requests.response_hours IS
    'The first-response promise made in the confirmation email, frozen at submission time so a later catalog change cannot rewrite history.';
COMMENT ON COLUMN public.contact_requests.client_token IS
    'Client-generated idempotency key. UNIQUE, so a double submit returns the first ticket instead of opening a second.';

-- ─── Ticket reference ───────────────────────────────────────────────────────
-- A sequence rather than a random string: references are read aloud on phone
-- calls and typed into search boxes, so they must be short and unambiguous.
-- The YYMM prefix makes the age of a ticket obvious without a lookup, and the
-- sequence guarantees uniqueness without a retry loop.
CREATE SEQUENCE IF NOT EXISTS public.contact_requests_ticket_seq AS bigint START WITH 1;

CREATE OR REPLACE FUNCTION public.next_contact_ticket_ref()
RETURNS text
LANGUAGE sql
VOLATILE
SET search_path = public, pg_temp
AS $$
    -- Modulo 10^6 so the reference stays six digits after a million tickets;
    -- the YYMM prefix keeps it unique long before that ever wraps.
    SELECT 'LB-'
        || to_char(now() AT TIME ZONE 'Asia/Kolkata', 'YYMM')
        || '-'
        || lpad((nextval('public.contact_requests_ticket_seq') % 1000000)::text, 6, '0');
$$;

COMMENT ON FUNCTION public.next_contact_ticket_ref() IS
    'Allocates the next human ticket reference (LB-YYMM-NNNNNN). Sequence-backed, so concurrent inserts never collide.';

ALTER TABLE public.contact_requests
    ALTER COLUMN ticket_ref SET DEFAULT public.next_contact_ticket_ref();

-- ─── Indexes ────────────────────────────────────────────────────────────────
-- Idempotency. This is the index that makes a double submit safe.
CREATE UNIQUE INDEX IF NOT EXISTS contact_requests_client_token_uniq
    ON public.contact_requests (client_token);

-- The operator queue: open work, newest first.
CREATE INDEX IF NOT EXISTS contact_requests_open_queue_idx
    ON public.contact_requests (team, created_at DESC)
    WHERE status IN ('new', 'triaged', 'in_progress', 'waiting_on_customer');

-- Breach watch: what is past its promise and still unanswered.
CREATE INDEX IF NOT EXISTS contact_requests_due_idx
    ON public.contact_requests (first_response_due_at)
    WHERE responded_at IS NULL AND status IN ('new', 'triaged', 'in_progress');

-- "What else has this person written to us about" — also what the gateway
-- throttle counts against.
--
-- Indexed on the bare column, NOT lower(email): Postgres matches expression
-- indexes syntactically, so an index on lower(email) is invisible to the
-- gateway's `email = $1` predicate and every public submission would seq-scan
-- the table. The gateway lower-cases through the Zod schema before insert, so
-- the stored value is already normalised and the plain column is correct.
CREATE INDEX IF NOT EXISTS contact_requests_email_created_idx
    ON public.contact_requests (email, created_at DESC);

-- Rate-limit lookups by source.
CREATE INDEX IF NOT EXISTS contact_requests_ip_created_idx
    ON public.contact_requests (ip_hash, created_at DESC)
    WHERE ip_hash IS NOT NULL;

CREATE INDEX IF NOT EXISTS contact_requests_topic_created_idx
    ON public.contact_requests (topic, created_at DESC);

-- Hot leads first, for the sales queue.
CREATE INDEX IF NOT EXISTS contact_requests_lead_idx
    ON public.contact_requests (lead_score DESC, created_at DESC)
    WHERE status IN ('new', 'triaged');

-- ─── updated_at ─────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.touch_contact_requests_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS contact_requests_touch_updated_at ON public.contact_requests;
CREATE TRIGGER contact_requests_touch_updated_at
    BEFORE UPDATE ON public.contact_requests
    FOR EACH ROW
    EXECUTE FUNCTION public.touch_contact_requests_updated_at();

-- ─── RLS ────────────────────────────────────────────────────────────────────
-- FORCE, so even the table owner is subject to policy. Exactly one policy, and
-- it is service_role: the gateway is the only writer, and nothing holding an
-- end-user session should ever read this table. No USING (true) for anon.
ALTER TABLE public.contact_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_requests FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "contact_requests service_role full access" ON public.contact_requests;
CREATE POLICY "contact_requests service_role full access"
    ON public.contact_requests
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

-- Deliberately NO policy for anon or authenticated. A submitter must not be
-- able to read back everyone else's messages, and the form posts through the
-- gateway rather than direct to PostgREST.

-- ─── Ticket status lookup ───────────────────────────────────────────────────
-- The one thing a submitter may read back: the status of THEIR OWN ticket, and
-- only when they can present both the reference and the email it was filed
-- under. SECURITY DEFINER because the caller has no rights on the table at all.
--
-- Two properties matter here:
--   • it returns no PII beyond what the caller already supplied — status and
--     timestamps only, never the message, phone or notes
--   • it requires BOTH factors, so a guessed sequential reference alone
--     discloses nothing. Guessing the reference is easy by design; guessing
--     the reference AND the email is not.
CREATE OR REPLACE FUNCTION public.get_contact_request_status(
    p_ticket_ref text,
    p_email text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_row public.contact_requests%ROWTYPE;
BEGIN
    IF p_ticket_ref IS NULL OR p_email IS NULL THEN
        RETURN jsonb_build_object('found', false);
    END IF;

    SELECT * INTO v_row
    FROM public.contact_requests
    WHERE ticket_ref = upper(btrim(p_ticket_ref))
      AND lower(email) = lower(btrim(p_email))
    LIMIT 1;

    IF NOT FOUND THEN
        -- Same shape for "wrong reference" and "wrong email", so the response
        -- cannot be used to confirm that a reference exists.
        RETURN jsonb_build_object('found', false);
    END IF;

    RETURN jsonb_build_object(
        'found', true,
        'ticket_ref', v_row.ticket_ref,
        'status', v_row.status,
        'topic', v_row.topic,
        'subject_line', v_row.subject_line,
        'team', v_row.team,
        'response_hours', v_row.response_hours,
        'submitted_at', v_row.created_at,
        'first_response_due_at', v_row.first_response_due_at,
        'responded_at', v_row.responded_at,
        'resolved_at', v_row.resolved_at
    );
END;
$$;

COMMENT ON FUNCTION public.get_contact_request_status(text, text) IS
    'Two-factor ticket lookup (reference + email). Returns status only, never message or contact details. Same negative response for unknown reference and wrong email.';

REVOKE ALL ON FUNCTION public.get_contact_request_status(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_contact_request_status(text, text) TO service_role;
