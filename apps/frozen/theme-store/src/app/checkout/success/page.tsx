import MarketplaceTaskTitle from '@/components/marketplace-task-title';
import Link from 'next/link';
import { CheckCircle, Download, Palette, LayoutDashboard, ArrowRight, Key } from '@letbuyy/ui';
import { ThemePurchaseSuccessToast } from '@/components/theme-action-feedback';
import type { Metadata } from 'next';
import { ThemeService } from '@/lib/theme-service';

export const metadata: Metadata = { title: 'Purchase Complete' };

type SuccessPageProps = {
    searchParams?: Promise<{
        theme?: string;
        purchase?: string;
    }>;
};

function formatInr(value: unknown): string {
    const amount = typeof value === 'number' && Number.isFinite(value) ? value : 0;
    return amount === 0 ? 'Free' : new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 0 }).format(amount);
}

export default async function SuccessPage({ searchParams }: SuccessPageProps) {
    const params = await searchParams;
    const themeSlug = params?.theme || '';
    const themeLabel = themeSlug ? themeSlug.replace(/-/g, ' ') : 'Selected theme';
    const receipt = params?.purchase ? await ThemeService.getThemeReceipt(params.purchase) : null;
    const purchase = receipt && typeof receipt.purchase === 'object' && receipt.purchase !== null ? receipt.purchase as Record<string, unknown> : {};

    return (
        <div className="container-main py-16 md:py-24 max-w-2xl mx-auto text-center">
            <ThemePurchaseSuccessToast themeSlug={themeSlug} />

            {/* Success Icon */}
            <div className="w-20 h-20 rounded-full bg-success/15 flex items-center justify-center mx-auto mb-6">
                <CheckCircle className="w-10 h-10 text-success" />
            </div>

            <MarketplaceTaskTitle artwork="legal">Purchase Complete!</MarketplaceTaskTitle>
            <p className="text-text-body text-lg mb-10">
                Thank you for your purchase. Payment verification has completed for this checkout attempt.
            </p>

            {/* Order Details */}
            <div className="glass-card p-6 text-left mb-10 space-y-4">
                <div className="flex items-center justify-between text-sm">
                    <span className="text-text-muted">Order</span>
                    <span className="text-text-heading font-medium">{receipt?.receipt_number || params?.purchase || 'Purchase recorded'}</span>
                </div>
                <div className="flex items-center justify-between text-sm">
                    <span className="text-text-muted">Theme</span>
                    <span className="text-text-heading font-medium capitalize">{themeLabel}</span>
                </div>
                <div className="flex items-center justify-between text-sm">
                    <span className="text-text-muted">Amount</span>
                    <span className="text-text-heading font-medium">{receipt ? formatInr(receipt.amount_inr) : formatInr(purchase.price_paid_inr)}</span>
                </div>
                <div className="flex items-center justify-between text-sm">
                    <span className="text-text-muted">Payment</span>
                    <span className="text-text-heading font-medium">{typeof purchase.status === 'string' ? purchase.status : 'completed'}</span>
                </div>

                <div className="border-t border-border pt-4">
                    <div className="flex items-center justify-between">
                        <div className="flex items-center gap-2">
                            <Key className="w-4 h-4 text-primary-light" />
                            <span className="text-sm text-text-muted">License Key</span>
                        </div>
                        <span className="text-sm text-text-heading font-medium">
                            {receipt?.license_key || (typeof purchase.license_key === 'string' ? purchase.license_key : 'Issued with completed purchase')}
                        </span>
                    </div>
                </div>

                <p className="text-[11px] text-text-subtle leading-relaxed">
                    GST invoice identifiers are generated by the gateway. Local development receipts use the configured dev GSTIN, and production receipts use the configured live GSTIN after the live tax setup is complete.
                </p>
            </div>

            {/* Next Steps */}
            <h2 className="text-xl font-bold mb-6">What&apos;s Next?</h2>
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 mb-10">
                <div className="glass-card p-5 text-center">
                    <div className="w-10 h-10 rounded-xl bg-primary/15 flex items-center justify-center mx-auto mb-3">
                        <Download className="w-5 h-5 text-primary-light" />
                    </div>
                    <p className="text-xs font-semibold text-text-heading mb-1">1. Install</p>
                    <p className="text-[11px] text-text-muted">Select a store before installing</p>
                </div>
                <div className="glass-card p-5 text-center">
                    <div className="w-10 h-10 rounded-xl bg-secondary/15 flex items-center justify-center mx-auto mb-3">
                        <Palette className="w-5 h-5 text-secondary" />
                    </div>
                    <p className="text-xs font-semibold text-text-heading mb-1">2. Customize</p>
                    <p className="text-[11px] text-text-muted">Open the merchant editor after install</p>
                </div>
                <div className="glass-card p-5 text-center">
                    <div className="w-10 h-10 rounded-xl bg-success/15 flex items-center justify-center mx-auto mb-3">
                        <LayoutDashboard className="w-5 h-5 text-success" />
                    </div>
                    <p className="text-xs font-semibold text-text-heading mb-1">3. Launch</p>
                    <p className="text-[11px] text-text-muted">Publish from your store editor</p>
                </div>
            </div>

            {/* CTA */}
            <div className="flex flex-col sm:flex-row items-center justify-center gap-3">
                <Link href={themeSlug ? `/install?theme=${themeSlug}` : '/dashboard/installations'} className="btn-primary py-3 px-6 flex items-center gap-2">
                    Install Theme
                    <ArrowRight className="w-4 h-4" />
                </Link>
                <Link href="/themes" className="btn-secondary py-3 px-6">
                    Browse More Themes
                </Link>
            </div>
        </div>
    );
}
