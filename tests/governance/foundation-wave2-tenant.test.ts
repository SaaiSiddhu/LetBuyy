import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import { createTenantGuardedSupabaseClient } from '../../services/api-gateway/src/tenant/tenant-scoped.ts';
import { TENANT_TABLES } from '../../services/api-gateway/src/tenant/tenant-tables.registry.ts';

const SITE_ID = '11111111-1111-4111-8111-111111111111';

function fakeBuilder() {
  return {
    select() { return this; },
    update() { return this; },
    delete() { return this; },
    insert() { return this; },
    upsert() { return this; },
    eq() { return this; },
    in() { return this; },
    filter() { return this; },
    match() { return this; },
    or() { return this; },
    maybeSingle() { return this; },
    single() { return this; },
    then(resolve: (value: unknown) => unknown, reject?: (reason: unknown) => unknown) {
      return Promise.resolve({ data: [], error: null }).then(resolve, reject);
    },
  };
}

function fakeClient() {
  return {
    from() {
      return fakeBuilder();
    },
  };
}

function executeQuery(query: unknown) {
  return Promise.resolve(query);
}

test('tenant table registry is generated and contains every required tenant table', () => {
  const registrySource = readFileSync('services/api-gateway/src/tenant/tenant-tables.registry.ts', 'utf8');
  assert.match(registrySource, /GENERATED by scripts\/generators\/generate-tenant-table-registry\.mjs/);
  assert.equal(TENANT_TABLES.length > 200, true);

  for (const table of [
    'payments',
    'payout_statements',
    'wallet_ledger_entries',
    'orders',
    'products',
    'sites',
  ]) {
    assert.equal(TENANT_TABLES.some((entry) => entry.table === table), true, `${table} missing from registry`);
  }
});

test('tenant guarded service-role client rejects unscoped execution for the full registry', async () => {
  const db = createTenantGuardedSupabaseClient(fakeClient() as never);

  for (const entry of TENANT_TABLES) {
    await assert.rejects(
      () => executeQuery(db.from(entry.table).select('*')),
      /requires a tenant\/owner predicate/,
      `${entry.table} must fail closed without tenant scope`,
    );

    const scopeColumn = entry.tenantColumn || entry.scopeColumns[0];
    assert.ok(scopeColumn, `${entry.table} must declare at least one scope column`);
    await assert.doesNotReject(
      () => executeQuery(db.from(entry.table).select('*').eq(scopeColumn, SITE_ID)),
      `${entry.table} must allow explicit scope through ${scopeColumn}`,
    );
  }
});

test('tenant guarded service-role client allows scoped mutations and blocks unscoped inserts', async () => {
  const db = createTenantGuardedSupabaseClient(fakeClient() as never);

  await assert.doesNotReject(
    () => executeQuery(db.from('orders').select('*').eq('store_id', SITE_ID)),
  );
  await assert.doesNotReject(
    () => executeQuery(db.from('orders').insert({ store_id: SITE_ID, total: 100 })),
  );
  await assert.rejects(
    () => executeQuery(db.from('orders').insert({ total: 100 })),
    /requires a tenant\/owner predicate/,
  );
  await assert.doesNotReject(
    () => executeQuery(db.from('sites').select('*').eq('id', SITE_ID)),
  );
});
