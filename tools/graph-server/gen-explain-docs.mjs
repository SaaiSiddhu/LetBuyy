#!/usr/bin/env node
// LCIS v6 — Documentation generation (Phase 16). Auto-generates the human + AI onboarding docs
// from the Explain model: a 30-minute onboarding, the per-domain explain, and the AI-context pack
// (single paste-ready source so any AI understands LetBuyy without scanning the repo).
import { writeDoc } from './omega-lib.mjs';
import { buildExplainIntel } from './explain-intel.mjs';

const x = buildExplainIntel();
if (x.error) { console.error(x.error); process.exit(1); }
const stamp = `\n\n> Auto-generated by \`pnpm graph:explain\` from the LCIS Explain model (repository truth in prose). Live values stay query-bound. Open the Explain mode at http://localhost:3333 for the interactive version.\n`;
console.log('\nLCIS v6 docs');

// ---- ONBOARDING.md ----
{
  const gs = x.gettingStarted;
  writeDoc('ONBOARDING.md', `# ${gs.title}\n\nA new engineer (or AI) should understand LetBuyy from this page alone. The interactive version is the **Explain mode** (default) at http://localhost:3333; **Atlas** is the deepest layer for investigation.\n\n${gs.steps.map((s, i) => `## ${i + 1}. ${s.t}\n${s.d}`).join('\n\n')}\n${stamp}`);
  console.log('  → docs/central-intelligence/ONBOARDING.md');
}

// ---- DOMAIN_EXPLAIN.md ----
{
  const rows = Object.values(x.nodes).map((n) => `| ${n.label} | ${n.criticality.split('—')[0].trim()} | ${n.purpose} | ${n.owner.join(', ')} | ${n.consumers.join(', ') || '—'} | ${n.failureImpact} |`).join('\n');
  writeDoc('DOMAIN_EXPLAIN.md', `# LetBuyy Domains — Explain (generated)\n\nPlain-language explanation of what every domain does, why it matters, who owns it, and what breaks if it fails. Technical detail (routes/rpcs/tables) is in the Explain mode "Show technical details" reveal and via \`/api/explain?node=<key>\`.\n\n| Domain | Criticality | Purpose | Owner | Failure blast (consumers) | Failure impact |\n|--------|-------------|---------|-------|---------------------------|----------------|\n${rows}\n${stamp}`);
  console.log('  → docs/central-intelligence/DOMAIN_EXPLAIN.md');
}

// ---- AI_CONTEXT_PACK.md (the single paste-ready source for Claude/Gemini/Codex) ----
{
  const blocks = Object.values(x.nodes).map((n) => '```\n' + n.aiContext + '\n```').join('\n\n');
  writeDoc('AI_CONTEXT_PACK.md', `# LetBuyy — AI Context Pack (generated)\n\nPaste any block below into Claude / Gemini / Codex so the model understands a LetBuyy domain **without scanning the repository**. Each block is repository-truth; live values are query-bound to the named LCIS endpoints.\n\n## Platform one-liner\n${x.gettingStarted.steps[0].d} ${x.gettingStarted.steps[1].d}\n\n## Per-domain context\n${blocks}\n${stamp}`);
  console.log('  → docs/central-intelligence/AI_CONTEXT_PACK.md');
}
console.log('  done.\n');
