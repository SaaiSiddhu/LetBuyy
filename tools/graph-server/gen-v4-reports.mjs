#!/usr/bin/env node
// Generates the LCIS v4 markdown reports from the live engines. Repository-truth only;
// live runtime/deploy values are explicitly marked as telemetry/API-bound, never fabricated.
// Run: pnpm graph:v4
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildMemoryIntel } from './memory-intel.mjs';
import { buildRuntimeIntel } from './runtime-intel.mjs';
import { buildDeploymentState } from './deployment-state.mjs';
import { buildExecutionIntel } from './execution-intel.mjs';
import { incidentResponse } from './incident-response.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'graphify-out');
const DOCS = join(ROOT, 'docs', 'central-intelligence');
if (!existsSync(DOCS)) mkdirSync(DOCS, { recursive: true });
const g = (f) => existsSync(join(OUT, f)) ? JSON.parse(readFileSync(join(OUT, f), 'utf8')) : null;
const W = (n, b) => { writeFileSync(join(DOCS, n), b); console.log('  →', 'docs/central-intelligence/' + n); };
const di = g('domain-intel.json'), db = g('db-intel.json'), infra = g('infra-intel.json');
const mem = buildMemoryIntel(), rt = buildRuntimeIntel(), ds = buildDeploymentState(infra), ex = buildExecutionIntel();
const stamp = (t) => `\n\n> Auto-generated by \`pnpm graph:v4\` on ${t} from repository truth. Live runtime/deploy values are telemetry/API-bound (marked), not fabricated.\n`;

console.log('\nLCIS v4 reports');

// ---- decision-intelligence.md (Phase 1) ----
{
  const byType = Object.entries(mem.summary.byType).map(([k, v]) => `${k} (${v})`).join(' · ');
  const sample = mem.decisions.filter((d) => /payment|refund|security|migration|theme/.test(d.type)).slice(0, 18)
    .map((d) => `| ${d.id} | ${d.type} | ${d.rule.replace(/\|/g, '\\|').slice(0, 130)} | ${d.source.split('/').pop()} |`).join('\n');
  W('decision-intelligence.md', `# Decision / Memory Intelligence (generated)

The decision graph — why rules, architecture and migrations exist — parsed from ${mem.summary.sources} governance/architecture/security docs + the ${mem.summary.migrationDecisions}-migration ledger. ${mem.summary.decisions} decisions: ${byType}.

## Sample decisions (payment / refund / security / migration / theme)
| id | type | rule | source |
|----|------|------|--------|
${sample}

## How to query
\`pnpm graph:memory rule "<keyword>"\` · \`why "<keyword>"\` · \`migration <n>\` · \`affecting "<domain>"\` · \`/api/memory?mode=rule&q=...\`

Latest migration decision: **${mem.summary.latestMigration?.decision || '—'}**.
${stamp(mem.summary.generatedAt)}`);
}

// ---- runtime-intelligence.md (Phase 2) ----
{
  const qg = rt.queueGraph.map((q) => `| ${q.queue} | ${q.producer} | ${q.consumers.join(', ')} |`).join('\n');
  const wg = rt.runtimeGraph.workers.map((w) => `| ${w.name} | ${w.routes.join(', ') || '—'} | ${w.crons.join(', ') || '·'} | ${w.r2.length ? '✓' : '·'} | ${w.cache ? '✓' : '·'} | ${w.hyperdrive ? '✓' : '·'} |`).join('\n');
  W('runtime-intelligence.md', `# Runtime Intelligence (generated)

Runtime topology from \`wrangler.toml\`. **Live latency/error/queue-depth values are NOT stored in the repository** — they emit to ${rt.summary.metricsSource}. Telemetry is wired (\`[observability]\` + \`analytics_engine_datasets\`) on: ${rt.telemetry.map((t) => t.worker).join(', ')}.

## Queue graph (producer → queue → consumer)
| Queue | Producer | Consumers |
|-------|----------|-----------|
${qg}

## Worker graph
| Worker | Routes | Crons | R2 | Cache | Hyperdrive |
|--------|--------|-------|:--:|:-----:|:----------:|
${wg}

## Live questions (telemetry-bound)
- **What is failing now / slow / backed up / failing endpoint** → ${rt.summary.liveSnapshot ? 'from `graphify-out/runtime-metrics.json` snapshot' : 'query the **RUNTIME_TELEMETRY** Analytics Engine dataset or `wrangler tail <worker>` — the repo declares the emission, not the values.'}
${stamp(rt.summary.generatedAt)}`);
}

// ---- deployment-state.md (Phase 3) ----
{
  W('deployment-state.md', `# Deployment State (generated)

Repository-**declared** intended state at HEAD. ⚠ ${ds.liveStateGap}

| Field | Value |
|-------|-------|
| HEAD | \`${ds.declared.headCommit}\` (${ds.declared.branch}) |
| Last tag | ${ds.declared.lastTag || '—'} |
| HEAD subject | ${ds.declared.headSubject || '—'} |
| Latest migration | \`${ds.declared.latestMigration?.file || '—'}\` (of ${ds.declared.totalMigrations}) |
| Workers | ${ds.targets.workers.join(', ')} |
| Vercel apps | ${ds.targets.vercelApps.join(', ')} |
| Secrets required | ${ds.targets.secretsRequired} |
| Deploy order | ${ds.gate.order.join(' → ')} (migrate gate ${ds.gate.migrateGate ? '✓' : '✗'}) |
| Rollback | \`${ds.rollback.script}\` ${ds.rollback.present ? '✓' : '✗'} |
${stamp(ds.generatedAt)}`);
}

// ---- incident-response.md (Phase 4) ----
{
  const ir = incidentResponse(di, db, infra, 'payments');
  W('incident-response.md', `# Incident Response Graph (generated)

Chain: **Incident → Route → RPC → Table → Queue → Worker → Owner → Deployment**. Worked example: a **payments** incident.

| Step | Value |
|------|-------|
| Root cause surface | ${ir.rootCause?.likelyOrigin} (money tables: ${ir.rootCauseSurface?.moneyTables?.length || 0}) |
| Blast radius | ${ir.blastRadius?.domains} domains · ${ir.blastRadius?.routes} routes · ${ir.blastRadius?.rpcs} rpcs · ${ir.blastRadius?.tables} tables |
| Affected domains | ${ir.affectedDomains?.join(', ')} |
| Affected merchants | ${ir.affectedMerchants} |
| Worker | ${ir.deployment?.worker} |
| Owner | ${(ir.owner || []).join(', ')} |
| Rollback | \`${ir.rollbackPath?.command}\` |
| Rollback policy | ${ir.rollbackPath?.policy} |

Query any domain/route/table: \`/api/incident-response?domain=<X>\` · \`pnpm graph:incident-response <X>\`.
${stamp(di?.summary.generatedAt || '')}`);
}

// ---- execution-intelligence.md (Phase 7) ----
{
  const bl = ex.blockers.map((b) => `| ${b.id} | ${b.severity} | ${b.status} | ${b.title.replace(/\|/g, '\\|').slice(0, 70)} |`).join('\n');
  const vd = ex.verdicts.map((v) => `| ${v.doc.split('/').pop()} | ${v.verdict} |`).join('\n');
  W('execution-intelligence.md', `# Execution Intelligence (generated)

What remains before launch — parsed from the blocker/gap/certification docs + code TODO markers. **Launch verdict: ${ex.summary.launchVerdict}** · open blockers ${ex.summary.openBlockers}/${ex.summary.totalBlockers} · code TODOs ${ex.summary.codeTodos}.

## Blockers
| ID | Severity | Status | Title |
|----|----------|--------|-------|
${bl}

## Certification verdicts
| Doc | Verdict |
|-----|---------|
${vd}

## What remains before launch
${ex.questions.whatRemainsBeforeLaunch.map((x) => '- ' + x).join('\n') || '- (none open)'}
${stamp(ex.summary.generatedAt)}`);
}

// ---- AUTONOMOUS_DISCOVERY_V4.md (Phase 11) ----
{
  W('AUTONOMOUS_DISCOVERY_V4.md', `# Autonomous Discovery v4 (generated)

| Surface | Count | Source |
|---------|------:|--------|
| Decisions | ${mem.summary.decisions} | governance/architecture docs (${mem.summary.sources}) |
| Migration decisions | ${mem.summary.migrationDecisions} | migration ledger (latest #${mem.summary.latestMigration?.n}) |
| Domains | ${di?.summary.domains ?? '—'} | domain-intel |
| Workers | ${rt.summary.workers} | wrangler |
| Queues | ${rt.summary.queues} | wrangler queues |
| Telemetry emitters | ${rt.summary.telemetryWorkers} | analytics_engine_datasets |
| Open blockers | ${ex.summary.openBlockers} | blocker report |
| Open gap docs | ${ex.summary.openGapDocs} | gap/cert docs |
| Latest migration | ${ds.declared.latestMigration?.n} | migrations |
| HEAD | \`${ds.declared.headCommit}\` (${ds.declared.branch}) | git |

New since v3: the decision/memory layer, the runtime topology graph (telemetry-bound), deployment-state, and the execution backlog. Live runtime/deploy metrics remain telemetry/API-bound (not fabricated). The 107 deterministic validators stay authoritative.
${stamp(ds.generatedAt)}`);
}

console.log('  done.\n');
