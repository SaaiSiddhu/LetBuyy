#!/usr/bin/env node
// Generates the LCIS v3 markdown intelligence reports from the live engines
// (domain-intel / payment-intel / security-intel / deployment-intel / merchant-intel +
// cross-domain). Repository-truth only — every number comes from the extractors.
// Run: pnpm graph:v3   (runs db/infra/domain extractors first, then this)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildPaymentIntel } from './payment-intel.mjs';
import { buildSecurityGraph } from './security-intel.mjs';
import { buildDeploymentIntel } from './deployment-intel.mjs';
import { buildMerchantIntel } from './merchant-intel.mjs';
import { blastDomain } from './cross-domain-engine.mjs';
import { runDiscovery } from './discovery-engine.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'graphify-out');
const DOCS = join(ROOT, 'docs', 'central-intelligence');
if (!existsSync(DOCS)) mkdirSync(DOCS, { recursive: true });
const g = (f) => existsSync(join(OUT, f)) ? JSON.parse(readFileSync(join(OUT, f), 'utf8')) : null;
const di = g('domain-intel.json'), db = g('db-intel.json'), infra = g('infra-intel.json');
if (!di || !db || !infra) { console.error('Missing intel JSON — run pnpm graph:db && graph:infra && graph:domain first.'); process.exit(1); }
const W = (name, body) => { writeFileSync(join(DOCS, name), body); console.log('  →', 'docs/central-intelligence/' + name); };
const stamp = `\n\n> Auto-generated by \`pnpm graph:v3\` on ${di.summary.generatedAt} from repository truth. Heuristic classifications are candidates; the 107 deterministic validators stay authoritative.\n`;

console.log('\nLCIS v3 reports');

// ---- DOMAIN_INTELLIGENCE_REPORT.generated.md (Phase 3) ----
{
  const rows = di.domains.map((d) => `| ${d.label} | ${d.counts.routes} | ${d.counts.rpcs} | ${d.counts.tables} | ${d.counts.policies} | ${d.money ? '✓' : ''} ${d.tenant ? 'T' : ''} | ${d.dependsOn.map((x) => x.domain).slice(0, 4).join(', ') || '—'} |`).join('\n');
  const edges = di.edges.sort((a, b) => b.strength - a.strength).slice(0, 20).map((e) => `| ${e.from} → ${e.to} | ${e.strength} | \`${e.via[0]}\` |`).join('\n');
  W('DOMAIN_INTELLIGENCE_REPORT.generated.md', `# Domain Intelligence Report (generated)

${di.summary.domains} business domains discovered by joining db-intel + infra-intel + the gateway route inventory. Coverage: routes ${di.summary.classifiedRoutes}/${di.summary.totalRoutes}, tables ${di.summary.classifiedTables}/${di.summary.totalTables}, rpcs ${di.summary.classifiedRpcs}/${di.summary.totalRpcs}; ${di.summary.crossDomainEdges} cross-domain edges.

## Domains
| Domain | routes | rpcs | tables | policies | money/tenant | depends on |
|--------|------:|----:|------:|--------:|:----:|-----------|
${rows}

## Strongest cross-domain couplings (RPC in A touches table in B)
| Edge | strength | example |
|------|--------:|---------|
${edges}

## Classification rules (deterministic, ordered specific→general)
${di.rules.map((r) => `- **${r.label}** — \`/${r.pattern}/\``).join('\n')}
${stamp}`);
}

// ---- merchant-intelligence.md (Phase 4) ----
{
  const m = buildMerchantIntel(di);
  const rows = m.stages.map((s) => `| ${s.stage} | ${s.apps.join(', ')} | ${s.routes} | ${s.rpcs} | ${s.tables} | ${s.dependsOn.join(', ') || '—'} |`).join('\n');
  W('merchant-intelligence.md', `# Merchant Intelligence (generated)

Merchant → Store → Products → Orders → Payments → Shipping → GST → Gift Cards → Themes mapped onto the domain graph. Merchant-facing apps: **${m.merchantFacingApps.join(', ')}**.

| Stage | Apps | routes | rpcs | tables | depends on |
|-------|------|------:|----:|------:|-----------|
${rows}

Totals across the merchant lifecycle: ${m.summary.totalRoutes} routes · ${m.summary.totalRpcs} rpcs · ${m.summary.totalTables} tables.
${stamp}`);
}

// ---- customer-journey-intelligence.md (Phase 5) ----
{
  const J = [
    ['Landing', ['storefront'], 'marketing-site / customer-web'],
    ['Storefront', ['storefront'], 'customer-web'],
    ['Product', ['products', 'collections'], 'customer-web'],
    ['Cart', ['orders'], 'customer-web'],
    ['Checkout', ['orders', 'discounts', 'gst', 'shipping'], 'customer-web'],
    ['Payment', ['payments', 'gift-cards'], 'customer-web → api-gateway'],
    ['Order', ['orders', 'inventory'], 'api-gateway → queue-workers'],
    ['Refund', ['refunds'], 'merchant-web'],
    ['Tracking', ['shipping', 'notifications'], 'customer-web'],
  ];
  const byKey = Object.fromEntries(di.domains.map((d) => [d.key, d]));
  const rows = J.map(([stage, ds, app]) => {
    const dd = ds.map((k) => byKey[k]).filter(Boolean);
    const routes = [...new Set(dd.flatMap((d) => d.routes))].length;
    const tables = [...new Set(dd.flatMap((d) => d.tables))].length;
    const money = dd.some((d) => d.money);
    return `| ${stage}${money ? ' 💰' : ''} | ${app} | ${ds.join(', ')} | ${routes} | ${tables} |`;
  }).join('\n');
  W('customer-journey-intelligence.md', `# Customer Journey Intelligence (generated)

Landing → Storefront → Product → Cart → Checkout → Payment → Order → Refund → Tracking, each stage resolved to its domains/routes/tables.

| Stage | Runtime | Domains | routes | tables |
|-------|---------|---------|------:|------:|
${rows}

The customer session is HS256 (\`CUSTOMER_SESSION_SECRET\`); checkout → payment crosses into the SECURITY DEFINER money RPCs (server-authoritative totals).
${stamp}`);
}

// ---- security-attack-graph.md (Phase 7) ----
{
  const sg = buildSecurityGraph(db, infra, di).graphs;
  W('security-attack-graph.md', `# Security Attack Graph (generated)

## Surfaces
| Graph | Key facts |
|-------|-----------|
| Identity | customer HS256 · merchant ES256/JWKS; domains: identity, merchant |
| JWT | secrets: ${sg.jwt.secrets.join(', ')} |
| OAuth | developer-portal PKCE (frozen — ARB to activate) |
| Webhook | HMAC-signed; tables: ${sg.webhook.tables.join(', ')} |
| Tenant isolation | ${sg.tenantIsolation.tenantTables} tenant tables · ${sg.tenantIsolation.withRls} RLS · ${sg.tenantIsolation.withForce} FORCE · ${sg.tenantIsolation.candidatesWithoutDetectedRls} candidates w/o detected RLS |
| RLS | ${sg.rls.policies} policies · ${sg.rls.publicUsingTrue} USING(true) (service-role-scoped) · ${sg.rls.serviceRole} service-role |

## If auth fails — the tenant boundary must hold
- routes exposed: **${sg.attackSurface.exposedIfAuthFails.routes.length}** · tenant tables at risk: **${sg.attackSurface.exposedIfAuthFails.tenantTablesAtRisk}** · workers: ${sg.attackSurface.exposedIfAuthFails.workers.join(', ')}
- backstop: ${sg.attackSurface.exposedIfAuthFails.backstop}
- money RPCs: ${sg.attackSurface.moneyRpcs} · SECURITY DEFINER fns: ${sg.attackSurface.securityDefinerFns} · production secrets: ${sg.attackSurface.productionSecrets}

## Deterministic backstop (authoritative, all green)
${['canonical-ledger-only', 'rls-force-coverage', 'no-public-using-true', 'no-blanket-service-role', 'identity-sole-issuer'].map((v) => '`' + v + '`').join(' · ')}
${stamp}`);
}

// ---- deployment-intelligence.md (Phase 8) ----
{
  const dp = buildDeploymentIntel(infra, di);
  const wf = dp.workflows.map((w) => `| ${w.file} | ${w.deploysWorkers ? '✓' : ''} | ${w.deploysVercel ? '✓' : ''} | ${w.runsMigrations ? '✓' : ''} | ${(w.gates || []).join(', ') || '—'} |`).join('\n');
  const sub = dp.subdomains.map((s) => `| ${s.host} | ${s.app} | ${s.via} |`).join('\n');
  W('deployment-intelligence.md', `# Deployment Intelligence (generated)

Pipeline: ${dp.pipeline.order.join(' → ')} (migrate gate ${dp.pipeline.migrateGate ? '✓' : '✗'}).

## GitHub Actions
| Workflow | workers | vercel | migrations | gates |
|----------|:------:|:-----:|:---------:|-------|
${wf}

## Targets
- **Workers (${dp.workers.length})**: ${dp.workers.map((w) => w.name).join(', ')}
- **Vercel apps (${dp.vercelApps.length})**: ${dp.vercelApps.join(', ')}
- **Queues**: producers ${dp.queues.producers.length}, consumers ${dp.queues.consumers.length}, crons ${dp.queues.crons.length}
- **Secrets required**: ${dp.secrets.required}
- **Providers**: ${dp.providers.join(', ')}

## Subdomains
| Host | App | Via |
|------|-----|-----|
${sub}

## Rollback
\`${dp.rollback.script}\` — requires ${dp.rollback.requires.join(', ')}; ${dp.rollback.policy}.
${stamp}`);
}

// ---- secret-intelligence.md (Phase 10) ----
{
  const rows = infra.secrets.map((name) => {
    const domains = di.domains.filter((d) => d.secrets.includes(name));
    const workers = [...new Set(domains.flatMap((d) => d.workers))];
    return `| \`${name}\` | ${(workers.length ? workers : ['letbuyy-api']).join(', ')} | ${domains.map((d) => d.key).join(', ') || '(platform-wide)'} |`;
  }).join('\n');
  W('secret-intelligence.md', `# Secret Intelligence (generated)

Secret → Service (worker) → Domains (features). All ${infra.secrets.length} secrets are set via \`wrangler secret put\` at deploy (\`production-deploy.yml\`); none are stored in the repository.

| Secret | Services | Domains / features |
|--------|----------|--------------------|
${rows}
${stamp}`);
}

// ---- AUTONOMOUS_DISCOVERY_V3.md (Phase 15) ----
{
  const r = runDiscovery(di, db, infra);
  const pref = r.candidates.unclassifiedTablesByPrefix.slice(0, 16).map((b) => `\`${b.prefix}_*\` (${b.count})`).join(' · ');
  W('AUTONOMOUS_DISCOVERY_V3.md', `# Autonomous Discovery v3 (generated)

Coverage — routes ${r.coverage.routes} (${r.coverage.routePct}%) · tables ${r.coverage.tables} (${r.coverage.tablePct}%) · rpcs ${r.coverage.rpcs} (${r.coverage.rpcPct}%).

## Unclassified (candidates — not dead code)
- **routes**: ${r.candidates.unclassifiedRoutes.map((x) => '`' + x + '`').join(', ') || '—'} (cross-cutting / reserved: ai, media, upload, resume)
- **table prefixes**: ${pref}
- ${r.candidates.note}

The 107 deterministic validators remain authoritative for dead-code / RLS / ledger correctness.
${stamp}`);
}

console.log('  done.\n');
