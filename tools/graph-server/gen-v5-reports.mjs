#!/usr/bin/env node
// Generates the LCIS v5 reports: V5_DISCOVERY_REPORT (Phase 1) + the live-operating reports.
// Repository-truth only; live metrics/revenue/merchant values are query-bound (marked), not fabricated.
// Run: pnpm graph:v5
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildRuntimeObservability } from './runtime-observability-intel.mjs';
import { buildMerchantIntelligence } from './merchant-intelligence.mjs';
import { buildRevenueIntelligence } from './revenue-intelligence.mjs';
import { buildDeploymentIntelligenceV5 } from './deployment-intelligence-v5.mjs';
import { buildSecurityIntelligenceV5 } from './security-intelligence-v5.mjs';
import { buildCustomerJourneyIntelligence } from './customer-journey-intelligence.mjs';
import { buildProductionReadiness } from './production-readiness-intel.mjs';
import { buildDecisionEngine } from './decision-engine-v5.mjs';
import { runDiscoveryV5 } from './autonomous-discovery-v5.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'graphify-out');
const DOCS = join(ROOT, 'docs', 'central-intelligence');
if (!existsSync(DOCS)) mkdirSync(DOCS, { recursive: true });
const g = (f) => existsSync(join(OUT, f)) ? JSON.parse(readFileSync(join(OUT, f), 'utf8')) : null;
const W = (n, b) => { writeFileSync(join(DOCS, n), b); console.log('  →', 'docs/central-intelligence/' + n); };
const infra = g('infra-intel.json'), db = g('db-intel.json'), di = g('domain-intel.json');
const obs = buildRuntimeObservability(), merch = buildMerchantIntelligence(), rev = buildRevenueIntelligence();
const sec = buildSecurityIntelligenceV5(), jr = buildCustomerJourneyIntelligence(), pr = buildProductionReadiness();
const de = buildDecisionEngine(), dep5 = buildDeploymentIntelligenceV5(), disc = runDiscoveryV5();
const stamp = `\n\n> Auto-generated by \`pnpm graph:v5\` from repository truth. Live runtime/revenue/merchant values are query-bound (marked), never fabricated. The 107 deterministic validators stay authoritative.\n`;

console.log('\nLCIS v5 reports');

// ---- V5_DISCOVERY_REPORT.md (Phase 1) ----
{
  const providers = infra?.summary.providers || [];
  W('V5_DISCOVERY_REPORT.md', `# LCIS v5 Discovery Report (Phase 1)

What data / telemetry / metrics / APIs / events exist across the LetBuyy runtime, and what intelligence LCIS now provides vs what stays live-bound.

## Platform inventory (repository truth)
| Platform | What exists in-repo | What's LIVE (not in repo) |
|----------|--------------------|--------------------------|
| Cloudflare Workers | ${infra?.summary.workers} workers + wrangler config, [observability], RUNTIME_TELEMETRY | request latency/errors/CPU/cold-starts (Analytics Engine) |
| Cloudflare Queues | ${infra?.summary.queueProducers.length} producers / ${infra?.summary.queueConsumers.length} consumers incl ${obs.deadLetterQueues.length} dead-letter | queue depth/retries/DLQ counts |
| Cron | ${obs.summary.crons.join(', ')} | last-run status |
| R2 / KV / Hyperdrive | R2 ${infra?.summary.r2.length}, Hyperdrive ${infra?.summary.hyperdrive ? '✓' : '✗'} | bucket sizes, cache hit-rate, pool stats |
| Supabase (Postgres) | ${db?.summary.tables} tables, ${db?.summary.functions} RPCs, ${db?.summary.policies} policies (migrations) | row data, query latency, connection counts |
| Vercel | ${infra?.summary.vercelApps.length} apps (deploy workflow) | build ids, live versions |
| Razorpay | server-side HMAC verify, payment_credentials | live transactions/settlements |
| Resend | RESEND_API_KEY, notification domain | delivery/bounce metrics |
| Analytics Engine | RUNTIME_TELEMETRY dataset binding | the actual metric series |
| Graphify / LCIS | full code+db+domain+infra+runtime+memory graphs | — |

## Providers detected
${providers.map((p) => '- ' + p).join('\n') || '- (see infra-intel)'} · Razorpay (payment HMAC) · Cloudflare · Vercel · Supabase

## What intelligence LCIS now provides (v5)
- Runtime observability graph (topology + metric sources), merchant model, revenue model + high-risk paths, deployment SPOFs, security control map, live incident answer, customer journey, **structural production readiness (${pr.summary.overall}%)**, AI decision ranking.

## What intelligence is still MISSING (live-bound — correctly not fabricated)
- Live latency/error/queue-depth (Analytics Engine), live revenue/refund amounts (ledger rows), top/inactive/broken merchants (site rows), funnel dropoff (analytics_event_stream), live deploy versions (Cloudflare/Vercel/Supabase APIs), load-tested capacity numbers.
${stamp}`);
}

// ---- runtime-observability-report.md (Phase 2) ----
{
  const m = Object.entries(obs.metrics).map(([k, v]) => `| ${k} | ${v.source} | ${v.status} |`).join('\n');
  W('runtime-observability-report.md', `# Runtime Observability Graph (generated)

${obs.summary.chainSpec}. ${obs.summary.metricsNote}

## Metric sources (all live-query-bound)
| Metric | Source | Status |
|--------|--------|--------|
${m}

Dead-letter queues: ${obs.deadLetterQueues.join(', ')} · telemetry emitters: ${obs.summary.telemetryEmitters}/${obs.summary.workers}.
${stamp}`);
}

// ---- production-readiness-report.md (Phase 9) ----
{
  const rows = pr.systems.map((s) => `| ${s.system} | ${s.score}% | ${s.blockers.join(', ') || '—'} | ${s.evidence.join('; ')} |`).join('\n');
  W('production-readiness-report.md', `# Production Readiness (generated) — STRUCTURAL (repo evidence)

${pr.summary.scope}

**Overall structural: ${pr.summary.overall}%** · launch verdict **${pr.summary.launchVerdict}** · open blockers ${pr.summary.openBlockers}. High structural completeness + NO-GO = the foundation is intact; the open blockers are launch-scope features.

| System | Score | Blockers | Evidence |
|--------|------:|----------|----------|
${rows}
${stamp}`);
}

// ---- decision-engine-report.md (Phase 10) ----
{
  W('decision-engine-report.md', `# AI Decision Engine (generated)

Launch verdict **${de.summary.launchVerdict}** · overall structural readiness ${de.summary.overallReadiness}%. ${de.summary.note}

## Fix next (ranked)
${de.fixNext.map((f) => `${f.rank}. **${f.id}** (${f.severity}) — ${f.title} _[${f.status}]_`).join('\n')}

## Highest risk
${de.highestRisk.map((r) => `- **${r.type}** ${r.ref}: ${r.detail}`).join('\n')}

## What blocks launch — ${de.blocksLaunch.verdict}
${de.blocksLaunch.blockers.map((b) => '- ' + b).join('\n')}

## What blocks 100 merchants
${de.blocksScale.blocks100Merchants.map((b) => '- ' + b).join('\n')}

## What blocks 10k users
${de.blocksScale.blocks10kUsers.map((b) => '- ' + b).join('\n')}

## What blocks 100k concurrent users
${de.blocksScale.blocks100kConcurrentUsers.map((b) => '- ' + b).join('\n')}
${stamp}`);
}

// ---- AUTONOMOUS_DISCOVERY_V5.md (Phase 14) ----
{
  W('AUTONOMOUS_DISCOVERY_V5.md', `# Autonomous Discovery v5 (generated) — candidates only

| Surface | Candidates | Note |
|---------|-----------:|------|
| Dead RPCs | ${disc.summary.deadRpcs} | mostly trigger/internal (verify with CREATE TRIGGER) |
| Dead routes | ${disc.summary.deadRoutes} | ${disc.deadRoutes.join(', ')} |
| Dead tables | ${disc.summary.deadTables} | event-sourcing/projection internals |
| Unused queues | ${disc.summary.unusedQueues} | naming-match heuristic |
| Unused workers | ${disc.summary.unusedWorkers} | — |
| Unused secrets | ${disc.summary.unusedSecrets} | — |
| Orphaned domains | ${disc.summary.orphanedDomains} | ${disc.orphanedDomains.join(', ')} |

${disc.summary.note}
${stamp}`);
}

console.log('  done.\n');
