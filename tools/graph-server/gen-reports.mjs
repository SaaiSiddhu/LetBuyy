#!/usr/bin/env node
// Generates the data-driven LCIS reports from db-intel.json + graph.json (real numbers only).
// Run: pnpm graph:reports  (regenerates docs/central-intelligence/*.generated.md)
import { readFileSync, writeFileSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDbIntel } from './db-intel.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DOCS = join(ROOT, 'docs', 'central-intelligence');
if (!existsSync(DOCS)) mkdirSync(DOCS, { recursive: true });

const db = buildDbIntel();
const s = db.summary;
let g = null;
try {
  g = JSON.parse(readFileSync(join(ROOT, 'graphify-out/graph.json'), 'utf8'));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
const gstat = g && { nodes: (g.nodes || []).length, edges: (g.links || []).length, commit: g.built_at_commit };

const money = db.functions.filter((f) => f.money);
const fmt = (n) => Number(n).toLocaleString();

// ---- DATABASE_INTELLIGENCE_REPORT.generated.md ----
const dbReport = `# Database Intelligence Report (generated)

> Auto-generated by \`pnpm graph:reports\` from ${s.migrationFiles} migrations + the gateway's \`db.rpc\` call sites. Regenerate after schema changes. The Graphify code graph does **not** index SQL bodies — this layer fills that gap.

## Schema inventory
| Object | Count |
|--------|------:|
| Tables | **${fmt(s.tables)}** |
| Functions / RPCs | **${fmt(s.functions)}** (SECURITY DEFINER ${s.securityDefiner}) |
| RLS policies | ${fmt(s.policies)} |
| Triggers | ${fmt(s.triggers)} |
| Indexes | ${fmt(s.indexes)} |
| Tables with RLS enabled | ${fmt(s.rlsTables)} (FORCE ${s.forceRlsTables}) |
| Tenant tables (site_id/store_id) | ${fmt(s.tenantTables)} |
| Money functions | ${fmt(s.moneyFunctions)} |
| RPCs invoked via gateway \`db.rpc\` | ${fmt(s.rpcsCalledByGateway)} |

## Money RPC → table flow (server-authoritative ledger)
Every money mutation is a SECURITY DEFINER RPC called via \`db.rpc\` (the \`canonical-ledger-only-validator\` enforces this). Idempotency + \`FOR UPDATE\` locks observed per function:

| RPC | SD | idem | lock | money tables | called by |
|-----|:--:|:----:|:----:|--------------|-----------|
${money.slice(0, 24).map((f) => `| \`${f.name}\` | ${f.securityDefiner ? '✓' : '✗'} | ${f.hasIdempotency ? '✓' : '·'} | ${f.forUpdate ? '✓' : '·'} | ${f.touches.filter((t) => s.moneyTablesPresent.includes(t)).join(', ') || '—'} | ${(f.callers[0] || '(internal/trigger)').replace('services/api-gateway/src/', '')} |`).join('\n')}

## Route → RPC → table chains (sample)
${Object.entries(db.routeRpc).filter(([r]) => /routes\/(orders|gift-cards|payouts|returns|settlements|inventory)/.test(r)).slice(0, 8).map(([route, rpcs]) => `- **${route.replace('services/api-gateway/src/', '')}** → ${rpcs.slice(0, 4).join(', ')}${rpcs.length > 4 ? '…' : ''} → tables: ${(db.routeTables[route] || []).slice(0, 8).join(', ') || '—'}`).join('\n')}

## Review candidates (heuristic — the deterministic validators are authoritative)
- **SECURITY DEFINER RPCs not invoked via gateway \`db.rpc\`:** ${s.functions - s.rpcsCalledByGateway} (many are trigger/internal functions, not dead code). Sample: ${db.functions.filter((f) => !f.callers.length && f.securityDefiner).slice(0, 12).map((f) => f.name).join(', ')}.
- **Tenant tables without a regex-detected RLS \`ENABLE\`:** ${s.tenantTablesWithoutRls.length} → ${s.tenantTablesWithoutRls.slice(0, 12).join(', ')}. *These are NOT confirmed violations — \`rls-force-coverage-validator\` passes, so they are either service-role-only/ledger tables or use an RLS pattern this parser does not detect. Verify before acting.*
- **Policies matching \`USING (true)\` (excluding service_role):** ${s.publicPolicies}. *\`no-public-using-true-validator\` passes, so these are service-role-scoped; this heuristic over-counts. Authoritative source is the validator.*

_${gstat ? `Graph: ${fmt(gstat.nodes)} nodes / ${fmt(gstat.edges)} edges @ ${(gstat.commit || '').slice(0, 8)}` : 'Code graph unavailable (graphify-out/graph.json has not been generated)'} · DB intel generated ${s.generatedAt}._
`;

writeFileSync(join(DOCS, 'DATABASE_INTELLIGENCE_REPORT.generated.md'), dbReport);
console.log('wrote docs/central-intelligence/DATABASE_INTELLIGENCE_REPORT.generated.md');
console.log(`  ${s.tables} tables · ${s.functions} functions · ${s.policies} policies · ${money.length} money RPCs`);
