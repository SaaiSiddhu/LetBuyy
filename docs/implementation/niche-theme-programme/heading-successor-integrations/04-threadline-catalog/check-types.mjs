import ts from 'typescript';
import { resolve, dirname } from 'node:path';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const rootNames = ['packages/theme-engine/src/first-party-theme-catalog.ts', 'packages/theme-engine/test/threadline-catalog-successor.test.ts'].map(path => resolve(path));
const project = resolve('packages/theme-engine/tsconfig.json');
const config = ts.readConfigFile(project, ts.sys.readFile);
if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, resolve('packages/theme-engine'));
const localRequire = createRequire(resolve('packages/theme-engine/package.json'));
const jsdomTypes = localRequire.resolve('@types/jsdom/package.json');
const nodeTypes = createRequire(jsdomTypes).resolve('@types/node/package.json');
const options = { ...parsed.options, noEmit: true, composite: false, incremental: false, declaration: false, declarationMap: false, emitDeclarationOnly: false, tsBuildInfoFile: undefined, outDir: undefined, types: ['node'], typeRoots: [dirname(dirname(nodeTypes)), dirname(dirname(jsdomTypes))] };
const program = ts.createProgram({ rootNames, options });
const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
const report = diagnostics.map(d => ({ path: d.file?.fileName || null, line: d.file && d.start !== undefined ? d.file.getLineAndCharacterOfPosition(d.start).line + 1 : null, code: d.code, message: ts.flattenDiagnosticMessageText(d.messageText, '\n') }));
writeFileSync(resolve('docs/implementation/niche-theme-programme/heading-successor-integrations/04-threadline-catalog/typecheck.json'), JSON.stringify({ rootNames, strict: options.strict, noEmit: options.noEmit, diagnostics: report, sourceFiles: program.getSourceFiles().map(file => file.fileName) }, null, 2) + '\n');
for (const d of report) process.stdout.write(JSON.stringify(d) + '\n');
process.stdout.write(`Scoped strict typecheck: ${diagnostics.length} diagnostics; no emit.\n`);
process.exitCode = diagnostics.length ? 1 : 0;
