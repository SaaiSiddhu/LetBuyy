// Run with: node --import tsx scripts/liquid-parity/build-threadline-catalog.mjs [--check]
// New distribution artifact only. Never regenerate applied migration 372 or merchant releases.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { createFirstPartyCatalogBundle } from '../../packages/theme-engine/src/first-party-theme-catalog.ts';
import { buildLiquidThemePackagePersistencePayload } from '../../packages/theme-engine/src/theme-bundle.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const bundle = createFirstPartyCatalogBundle('letbuyy-sense');
const persistence = buildLiquidThemePackagePersistencePayload(bundle);
const document = { themeId: 'letbuyy-sense', experienceId: 'sense', rendererEngine: 'liquid', liquidRenderingCanary: true, themeSettings: bundle.config.settings_data.current, liquidBundle: bundle, templates: bundle.templates, sections: {} };
const digest = createHash('sha256').update(JSON.stringify(bundle)).digest('hex');
const payload = JSON.stringify({ document, sectionSchemas: persistence.schemaManifest.section_schemas, settingsSchema: persistence.schemaManifest.settings_schema, renderer: bundle.renderer });
// Reuse the established data-only quote tag recognized by migration safety.
// Fail closed if future theme source would terminate the SQL literal.
if (payload.includes('$liquidbundle$')) throw new Error('Theme artifact contains the reserved SQL quote delimiter');
const forward = `-- Generated by build-threadline-catalog.mjs. Canonical Liquid package SHA-256: ${digest}
-- Updates only the public sense catalog version. Installed instances/drafts/releases remain captured.
BEGIN;
DO $promotion$
DECLARE t public.themes; artifact jsonb := $liquidbundle$${payload}$liquidbundle$::jsonb; previous jsonb;
BEGIN
 SELECT * INTO STRICT t FROM public.themes WHERE id='7b669c70-0000-4000-8000-000000000002' AND slug='letbuyy-sense' AND owned_by_site_id IS NULL AND NOT is_site_private FOR UPDATE;
 IF t.config->>'threadlineArtifactSha256'='${digest}' AND t.default_template=artifact->'document' AND t.section_schemas=artifact->'sectionSchemas' AND t.settings_schema=artifact->'settingsSchema' THEN RETURN; END IF;
 previous := coalesce(t.config->'threadlineCatalogRollback',jsonb_build_object('id',t.id,'name',t.name,'description',t.description,'long_description',t.long_description,'version',t.version,'sort_order',t.sort_order,'category',t.category,'thumbnail_url',t.thumbnail_url,'preview_url',t.preview_url,'default_template',t.default_template,'section_schemas',t.section_schemas,'settings_schema',t.settings_schema,'renderer_manifest',t.renderer_manifest,'config',t.config));
 UPDATE public.themes SET name='Threadline', description='Editorial apparel with silhouette discovery, garment measurements and size-aware shopping.',
 long_description='Threadline 2.0.0. Configure your own campaign media, collections, independently sold outfit products and garment facts. Shared LetBuyy checkout and buyer identity.',
 version='${bundle.package.version}',sort_order=0,category='fashion',thumbnail_url='/theme-previews/threadline-2.0.0.webp',preview_url='/theme-preview/letbuyy-sense',
 default_template=artifact->'document',section_schemas=artifact->'sectionSchemas',settings_schema=artifact->'settingsSchema',renderer_manifest=artifact->'renderer',
 config=coalesce(t.config,'{}'::jsonb)||jsonb_build_object('threadlineCatalogRollback',previous,'threadlineArtifactSha256','${digest}','designVersion','${bundle.package.version}'),updated_at=now()
 WHERE id=t.id;
END;
$promotion$;
COMMIT;
`;
const down = `-- Restores the exact prior public catalog metadata/document. No merchant data is rewritten.
BEGIN;
DO $rollback$
DECLARE saved jsonb; prior public.themes;
BEGIN
 SELECT config->'threadlineCatalogRollback' INTO saved FROM public.themes WHERE id='7b669c70-0000-4000-8000-000000000002' AND owned_by_site_id IS NULL AND NOT is_site_private FOR UPDATE;
 IF saved IS NULL THEN RETURN; END IF;
 prior := jsonb_populate_record(NULL::public.themes,saved);
 UPDATE public.themes SET name=prior.name,description=prior.description,long_description=prior.long_description,version=prior.version,sort_order=prior.sort_order,category=prior.category,thumbnail_url=prior.thumbnail_url,preview_url=prior.preview_url,default_template=prior.default_template,section_schemas=prior.section_schemas,settings_schema=prior.settings_schema,renderer_manifest=prior.renderer_manifest,config=prior.config,updated_at=now() WHERE id=prior.id AND owned_by_site_id IS NULL AND NOT is_site_private;
END;
$rollback$;
COMMIT;
`;
for (const [name, source] of [['database/supabase/migrations/382_threadline_catalog_v2.sql', forward], ['database/supabase/rollback/382_threadline_catalog_v2.rollback.sql', down]]) {
  const file = resolve(root, name);
  if (process.argv.includes('--check')) { if (readFileSync(file, 'utf8') !== source) throw new Error(`Stale Threadline artifact: ${name}`); }
  else writeFileSync(file, source);
}
console.info(JSON.stringify({ theme: bundle.package.slug, version: bundle.package.version, sha256: digest, check: process.argv.includes('--check') }));
