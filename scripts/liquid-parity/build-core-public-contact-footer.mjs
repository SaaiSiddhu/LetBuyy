#!/usr/bin/env node
// Regenerate only the paired, guarded Core catalog footer migration. The
// accepted migration 368 and its seed stay immutable; merchant-owned themes,
// drafts, and published releases are outside this catalog update.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createLetbuyyCoreLiquidThemeBundleFixture } from '../../packages/theme-engine/src/theme-bundle-core.ts';

if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Supported option: --check');
const check = process.argv.includes('--check');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const oldBundle = JSON.parse(readFileSync(resolve(root, 'database/supabase/seeds/generated/letbuyy-core-liquid-bundle.json'), 'utf8'));
const newBundle = createLetbuyyCoreLiquidThemeBundleFixture();
const before = oldBundle.sections.footer;
const current = newBundle.sections.footer;
const stable = value => JSON.stringify(value, (_key, item) =>
  item && typeof item === 'object' && !Array.isArray(item)
    ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a.localeCompare(b)))
    : item);
if (!before || !current || stable(before) !== stable(current)) {
  throw new Error('Frozen Core footer factory changed; review a separate catalog release');
}
for (const section of Object.keys(newBundle.sections)) {
  if (section !== 'footer' && stable(newBundle.sections[section]) !== stable(oldBundle.sections[section])) {
    throw new Error(`Core section ${section} changed; review a separate catalog migration`);
  }
}
// Migration 426 is a versioned catalog patch. Keep the package factory and
// migration 368 seed byte-identical to their admitted versions; changing those
// factories would also mutate every frozen default theme bundle.
const originalContact = [
  '      {% if section.settings.contactEmail != blank %}<p><a href="mailto:{{ section.settings.contactEmail }}">{{ section.settings.contactEmail }}</a></p>{% endif %}',
  '      {% if section.settings.contactPhone != blank %}<p><a href="tel:{{ section.settings.contactPhone }}">{{ section.settings.contactPhone }}</a></p>{% endif %}',
].join('\n');
const publicContact = [
  '      {% assign contact_email = section.settings.contactEmail | default: shop.contact_email %}',
  '      {% if contact_email == "help@letbuyy.com" %}{% assign contact_email = shop.contact_email %}{% endif %}',
  '      {% assign contact_phone = section.settings.contactPhone | default: shop.contact_phone %}',
  '      {% if contact_email != blank %}<p><a href="mailto:{{ contact_email }}">{{ contact_email }}</a></p>{% endif %}',
  '      {% if contact_phone != blank %}<p><a href="tel:{{ contact_phone }}">{{ contact_phone }}</a></p>{% endif %}',
].join('\n');
if (typeof before.source !== 'string' || before.source.split(originalContact).length !== 2) {
  throw new Error('Frozen Core footer contact block changed; review a separate catalog migration');
}
const after = { ...before, source: before.source.replace(originalContact, publicContact) };
const json = value => {
  const serialized = JSON.stringify(value);
  if (serialized.includes('$corefooterjson$')) throw new Error('Unsafe Core footer delimiter');
  return `$corefooterjson$${serialized}$corefooterjson$::jsonb`;
};
function sql(rollback) {
  const from = rollback ? after : before;
  const to = rollback ? before : after;
  return `-- 426 — ${rollback ? 'Rollback' : 'Publish'} the opt-in public contact footer on the unowned Core catalog only.
-- Generated by scripts/liquid-parity/build-core-public-contact-footer.mjs.
-- Existing site-owned themes, editor drafts, and published releases are immutable.
BEGIN;
SET LOCAL search_path = pg_catalog, public;
DO $core_footer_426$
DECLARE
  v_template jsonb;
  v_bundle jsonb;
  v_current jsonb;
  v_from jsonb := ${json(from)};
  v_to jsonb := ${json(to)};
BEGIN
  SELECT default_template INTO v_template FROM public.themes
   WHERE slug = 'letbuyy-core' AND owned_by_site_id IS NULL
     AND NOT COALESCE(is_site_private, false) FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unowned canonical Core catalog is unavailable'; END IF;
  v_bundle := v_template->'liquidBundle';
  IF v_bundle#>>'{package,slug}' IS DISTINCT FROM 'letbuyy-core-liquid'
     OR v_bundle#>>'{renderer,engine}' IS DISTINCT FROM 'liquid' THEN
    RAISE EXCEPTION 'Unexpected Core package or renderer';
  END IF;
  v_current := v_bundle#>'{sections,footer}';
  IF v_current IS DISTINCT FROM v_from AND v_current IS DISTINCT FROM v_to THEN
    RAISE EXCEPTION 'Unexpected Core catalog footer';
  END IF;
  IF v_current IS NOT DISTINCT FROM v_from THEN
    v_bundle := jsonb_set(v_bundle, '{sections,footer}', v_to, false);
    UPDATE public.themes
       SET default_template = jsonb_set(v_template, '{liquidBundle}', v_bundle, false),
           updated_at = now()
     WHERE slug = 'letbuyy-core' AND owned_by_site_id IS NULL
       AND NOT COALESCE(is_site_private, false);
  END IF;
END;
$core_footer_426$;
COMMIT;
`;
}
const outputs = [
  ['database/supabase/migrations/426_core_public_contact_footer.sql', sql(false)],
  ['database/supabase/rollback/426_core_public_contact_footer.rollback.sql', sql(true)],
];
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  if (existsSync(target)) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Refusing to rewrite accepted migration ${path}`);
  } else if (check) {
    throw new Error(`Missing generated Core footer migration ${path}`);
  } else {
    writeFileSync(target, content);
  }
}
console.info(JSON.stringify({ check, outputs: outputs.map(([path]) => path) }));
