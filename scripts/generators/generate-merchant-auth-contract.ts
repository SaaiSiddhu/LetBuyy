import { readFileSync, writeFileSync } from 'node:fs';
import { MERCHANT_NATIVE_ENVIRONMENTS, merchantNativeCallback } from '../../packages/auth-core/src/merchant-native-registry';

const path = 'apps/merchant/mobile/lib/services/merchant_auth_contract.g.dart';
const entries = MERCHANT_NATIVE_ENVIRONMENTS.map(environment => {
    return `    '${environment}': {\n      'merchant_android': '${merchantNativeCallback('merchant_android', 'android_https', environment)}',\n      'merchant_ios': '${merchantNativeCallback('merchant_ios', 'ios_session', environment)}',\n    },`;
}).join('\n');
const source = `// Generated by scripts/generators/generate-merchant-auth-contract.ts. Do not edit.\n// Authority: @letbuyy/auth-core Merchant first-party client registry.\nconst merchantAuthCallbacks = <String, Map<String, String>>{\n${entries}\n};\n`;
if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== source) throw new Error('Merchant native auth contract is stale');
} else writeFileSync(path, source);
