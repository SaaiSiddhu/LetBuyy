#!/usr/bin/env node
/**
 * generate-design-tokens.mjs — keep the DTCG interchange file (tokens.json) in
 * parity with the authoring source of truth (packages/typescript/ui/src/tokens.ts),
 * and optionally emit a static CSS custom-property reference for non-React /
 * documentation consumers.
 *
 * The authoring source remains tokens.ts (hand-maintained, imported across the
 * web apps). tokens.json is its W3C-DTCG projection used for Figma sync and
 * cross-platform codegen; the Flutter projection is produced separately by
 * generate-mobile-tokens.mjs. This script does NOT invert that pipeline — it
 * guards it. (See docs/design-system/foundations.md and
 * docs/governance/skipped-human-decisions.md.)
 *
 * Pure Node (no tsx/esbuild) so it runs in any CI lane and in the pre-commit hook.
 *
 * Usage:
 *   node scripts/generators/generate-design-tokens.mjs            # validate structure + refs
 *   node scripts/generators/generate-design-tokens.mjs --check    # also fail on tokens.ts drift (CI)
 *   node scripts/generators/generate-design-tokens.mjs --emit-css # write docs/design-system/tokens.reference.css
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const TOKENS_JSON = join(ROOT, 'packages', 'typescript', 'ui', 'tokens.json');
const TOKENS_TS = join(ROOT, 'packages', 'typescript', 'ui', 'src', 'tokens.ts');
const CSS_OUT = join(ROOT, 'docs', 'design-system', 'tokens.reference.css');

const CHECK = process.argv.includes('--check');
const EMIT_CSS = process.argv.includes('--emit-css');

const dtcg = JSON.parse(readFileSync(TOKENS_JSON, 'utf8'));
const tsSource = readFileSync(TOKENS_TS, 'utf8');
const errors = [];

// ── 1. Resolve every DTCG {alias} reference ──────────────────────────────────
function getByPath(obj, path) {
    return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
}
function resolveValue(value, seen = new Set()) {
    if (typeof value !== 'string') return value;
    const m = value.match(/^\{([^}]+)\}$/);
    if (!m) return value;
    if (seen.has(m[1])) { errors.push(`circular reference: {${m[1]}}`); return undefined; }
    seen.add(m[1]);
    const node = getByPath(dtcg, m[1]);
    if (!node || node.$value === undefined) { errors.push(`unresolved reference: {${m[1]}}`); return undefined; }
    return resolveValue(node.$value, seen);
}

// Walk all leaves ($value), collect resolved color/dimension tokens.
const flat = {};
function walk(node, path) {
    if (node && typeof node === 'object') {
        if (Object.prototype.hasOwnProperty.call(node, '$value')) {
            flat[path] = resolveValue(node.$value);
            return;
        }
        for (const [k, v] of Object.entries(node)) {
            if (k.startsWith('$')) continue;
            walk(v, path ? `${path}.${k}` : k);
        }
    }
}
walk(dtcg, '');

// ── 2. Parity anchors: these must match tokens.ts exactly ────────────────────
// Each anchor is a value that must appear literally in tokens.ts. This catches
// the high-value drift (brand, status, scales) without re-implementing the TS.
const anchors = [
    ['color.primitive.purple.500', '#8B5CF6'],
    ['color.primitive.purple.600', '#7C3AED'],
    ['color.primitive.purple.700', '#6D28D9'],
    ['color.primitive.gray.900', '#111827'],
    ['color.primitive.gray.200', '#E5E7EB'],
    ['color.primitive.green.500', '#22C55E'],
    ['color.primitive.red.500', '#EF4444'],
    ['color.primitive.blue.500', '#3B82F6'],
    ['color.primitive.amber.500', '#F59E0B'],
    ['dimension.space.xs', '4px'],
    ['dimension.space.lg', '16px'],
    ['dimension.space.7xl', '96px'],
    ['dimension.radius.full', '999px'],
    ['typography.fontSize.body', '14px'],
    ['typography.fontSize.page-title', '24px'],
];

for (const [path, expected] of anchors) {
    const got = flat[path];
    if (got !== expected) errors.push(`tokens.json ${path} = ${JSON.stringify(got)}, expected ${JSON.stringify(expected)}`);
    if (CHECK && !tsSource.includes(`'${expected}'`)) {
        errors.push(`DRIFT: value ${expected} (for ${path}) not found in tokens.ts — interchange file is out of sync with the source of truth`);
    }
}

// ── 3. Optional CSS reference emission ───────────────────────────────────────
if (EMIT_CSS && errors.length === 0) {
    const lines = [
        '/* GENERATED by scripts/generators/generate-design-tokens.mjs from tokens.json. Do not edit. */',
        '/* Static reference of the LIGHT scheme semantic colors + scales for non-React/doc consumers. */',
        ':root {',
    ];
    for (const [path, val] of Object.entries(flat)) {
        if (path.startsWith('color.semantic.light.')) lines.push(`  --lb-color-${path.split('.').pop()}: ${val};`);
        else if (path.startsWith('dimension.space.')) lines.push(`  --lb-space-${path.split('.').pop()}: ${val};`);
        else if (path.startsWith('dimension.radius.')) lines.push(`  --lb-radius-${path.split('.').pop()}: ${val};`);
    }
    lines.push('}', '');
    writeFileSync(CSS_OUT, lines.join('\n'));
    console.log(`Emitted ${CSS_OUT}`);
}

// ── Report ───────────────────────────────────────────────────────────────────
const leafCount = Object.keys(flat).length;
console.log(`tokens.json: ${leafCount} resolved token(s).`);
if (errors.length) {
    console.error('\n✖ Design-token interchange validation FAILED:');
    for (const e of errors) console.error('  - ' + e);
    process.exit(1);
}
console.log('✔ tokens.json valid' + (CHECK ? ' and in parity with tokens.ts.' : '.'));
process.exit(0);
