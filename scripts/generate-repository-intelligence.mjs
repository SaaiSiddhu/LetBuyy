function routeFromNextAppFile(file) {
  const marker = "/src/app/";
  if (!file.includes(marker)) return null;
  const after = file.split(marker)[1];
  const fileName = path.basename(after);
  if (!["page.tsx", "page.ts", "layout.tsx", "route.ts", "loading.tsx", "error.tsx", "not-found.tsx"].includes(fileName)) {
    return null;
  }
  const dir = path.dirname(after);
  const segments = dir === "." ? [] : dir.split("/");
  const routeSegments = segments.filter((segment) => !(segment.startsWith("(") && segment.endsWith(")")));
  return {
    route: `/${routeSegments.join("/")}`.replace(/\/+/g, "/"),
    kind: fileName.replace(/\.(tsx|ts)$/, ""),
  };
}

