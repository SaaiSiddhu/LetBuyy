function markdownList(values, limit = 24) {
  const sliced = values.slice(0, limit);
  if (!sliced.length) return "- None detected in current scan.";
  const rows = sliced.map((value) => `- ${value}`);
  if (values.length > limit) rows.push(`- ... ${values.length - limit} additional entries omitted here; see master intelligence catalog.`);
  return rows.join("\n");
}

function compactFileTable(summaries, limit = 40) {
  const rows = summaries.slice(0, limit).map((summary) => {
    const route = summary.nextRoute ? `${summary.nextRoute.kind}:${summary.nextRoute.route}` : summary.honoRoutes.length ? `hono:${summary.honoRoutes.length}` : "";
    return `| \`${summary.file}\` | ${summary.area} | ${summary.lines} | ${route || "source"} | ${summary.flags.slice(0, 4).join(", ") || "none"} |`;
  });
  if (!rows.length) return "No matching files found in current scan.";
  return ["| File | Area | Lines | Route Surface | Flags |", "|---|---:|---:|---|---|", ...rows, summaries.length > limit ? `| ... | ${summaries.length - limit} more |  | See master intelligence |  |` : ""]
    .filter(Boolean)
    .join("\n");
}

