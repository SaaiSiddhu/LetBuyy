function extractImports(text) {
  const imports = [];
  for (const match of text.matchAll(/^\s*import\s+(?:[^'"]+\s+from\s+)?['"]([^'"]+)['"]/gm)) {
    imports.push(match[1]);
  }
  for (const match of text.matchAll(/^\s*export\s+[^'"]+\s+from\s+['"]([^'"]+)['"]/gm)) {
    imports.push(match[1]);
  }
  return unique(imports);
}

function extractEnvNames(text) {
  const names = [];
  for (const match of text.matchAll(/process\.env\.([A-Z0-9_]+)/g)) names.push(match[1]);
  for (const match of text.matchAll(/\bc\.env\.([A-Z0-9_]+)/g)) names.push(match[1]);
  for (const match of text.matchAll(/\benv\.([A-Z0-9_]+)/g)) names.push(match[1]);
  for (const match of text.matchAll(/\b([A-Z][A-Z0-9_]{3,})\s*:/g)) {
    if (match[1].includes("_")) names.push(match[1]);
  }
  return unique(names);
}

function extractHonoRoutes(text) {
  const routes = [];
  for (const match of text.matchAll(/\b(?:router|app|api)\.(get|post|put|patch|delete|options|route|use)\(\s*['"`]([^'"`]+)['"`]/g)) {
    routes.push({ method: match[1].toUpperCase(), path: match[2] });
  }
  return routes;
}

function extractNextHandlers(text) {
  const handlers = [];
  for (const match of text.matchAll(/export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE|OPTIONS)/g)) {
    handlers.push(match[1]);
  }
  return unique(handlers);
}

function extractSqlObjects(text) {
  const objects = {
    tables: [],
    alteredTables: [],
    indexes: [],
    policies: [],
    functions: [],
    triggers: [],
    rlsTables: [],
    references: [],
  };
  for (const match of text.matchAll(/create\s+table\s+(?:if\s+not\s+exists\s+)?([\w."]+)/gi)) objects.tables.push(match[1].replaceAll('"', ""));
  for (const match of text.matchAll(/alter\s+table\s+(?:if\s+exists\s+)?([\w."]+)/gi)) objects.alteredTables.push(match[1].replaceAll('"', ""));
  for (const match of text.matchAll(/create\s+(?:unique\s+)?index\s+(?:if\s+not\s+exists\s+)?([\w."]+)/gi)) objects.indexes.push(match[1].replaceAll('"', ""));
  for (const match of text.matchAll(/create\s+policy\s+"?([^"\n]+)"?\s+on\s+([\w."]+)/gi)) objects.policies.push(`${match[1].trim()} on ${match[2].replaceAll('"', "")}`);
  for (const match of text.matchAll(/create\s+(?:or\s+replace\s+)?function\s+([\w."]+)/gi)) objects.functions.push(match[1].replaceAll('"', ""));
  for (const match of text.matchAll(/create\s+trigger\s+([\w."]+)/gi)) objects.triggers.push(match[1].replaceAll('"', ""));
  for (const match of text.matchAll(/alter\s+table\s+([\w."]+)\s+enable\s+row\s+level\s+security/gi)) objects.rlsTables.push(match[1].replaceAll('"', ""));
  for (const match of text.matchAll(/references\s+([\w."]+)\s*\(/gi)) objects.references.push(match[1].replaceAll('"', ""));
  for (const key of Object.keys(objects)) objects[key] = unique(objects[key]);
  return objects;
}

