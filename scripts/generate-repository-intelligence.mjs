function summarizeFile(file, text) {
  const ext = path.extname(file) || path.basename(file);
  const lines = text ? text.split(/\r?\n/).length : 0;
  const stat = fs.statSync(path.join(root, file));
  const nextRoute = routeFromNextAppFile(file);
  const imports = extractImports(text);
  const envNames = extractEnvNames(text);
  const honoRoutes = extractHonoRoutes(text);
  const nextHandlers = extractNextHandlers(text);
  const sql = ext === ".sql" ? extractSqlObjects(text) : null;
  const flags = [];
  if (text.includes('"use client"') || text.includes("'use client'")) flags.push("client component");
  if (text.includes("localStorage")) flags.push("uses localStorage");
  if (text.includes("console.log")) flags.push("console.log");
  if (text.includes("console.error")) flags.push("console.error");
  if ([".ts", ".tsx"].includes(ext) && /\bany\b/.test(text)) flags.push("TypeScript any");
  if (text.includes("style={{")) flags.push("inline React style");
  if (/TODO|FIXME|HACK/.test(text)) flags.push("TODO/FIXME/HACK");
  if (/SUPABASE_SERVICE_ROLE_KEY|service_role/i.test(text)) flags.push("service role reference");
  if (/csrf|CSRF/.test(text)) flags.push("CSRF reference");
  if (/razorpay|stripe|paypal/i.test(text)) flags.push("payment provider reference");
  if (/(rzp_(?:live|test)_[A-Za-z0-9]+|(?:sk|pk)_(?:live|test)_[A-Za-z0-9]+)/.test(text)) flags.push("hardcoded payment key id");
  if (/webhook/i.test(text)) flags.push("webhook reference");
  if (/rateLimit|rate-limit|ratelimit/i.test(text)) flags.push("rate limiting reference");
  if (/update_updated_at_column|update_modified_at/.test(text)) flags.push("non-standard updated_at trigger name");
  if (/items\s+JSONB/i.test(text)) flags.push("orders JSONB items schema");
  return {
    file,
    ext,
    area: classifyArea(file),
    appRoot: appRootForFile(file),
    bytes: stat.size,
    lines,
    nextRoute,
    imports,
    envNames,
    honoRoutes,
    nextHandlers,
    sql,
    flags: unique(flags),
    leading: firstLines(text, 4),
  };
}

function listFilesUnder(prefix, files) {
  return files.filter((file) => file === prefix || file.startsWith(`${prefix}/`));
}

function countBy(files, fn) {
  const map = new Map();
  for (const item of files) {
    const key = fn(item);
    map.set(key, (map.get(key) || 0) + 1);
  }
  return [...map.entries()].sort((a, b) => a[0].localeCompare(b[0]));
}

