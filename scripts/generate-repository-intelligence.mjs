function main() {
  writeFile("AGENTS.md", buildRootAgents());
  writeFile("docs/README.md", buildIndexDoc());
  ensureDir("docs/architecture");
  writeFile("docs/architecture/master-system-intelligence.md", buildMasterIntelligence());
  for (const topic of topicDirs) {
    ensureDir(`docs/${topic}`);
    if (topic === "architecture") {
      writeFile(`docs/${topic}/README.md`, `${buildTopicDoc(topic)}\n\n## Master Document\n\n- [Master System Intelligence](./master-system-intelligence.md)\n`);
    } else {
      writeFile(`docs/${topic}/README.md`, buildTopicDoc(topic));
    }
  }
  for (const target of appTargets) writeFile(target.output, buildAppAgents(target));
  for (const target of packageTargets) writeFile(target.output, buildPackageAgents(target));
  const report = {
    generatedAt: now,
    sourceFiles: sourceFiles.length,
    packages: packages.length,
    migrations: migrationFiles.length,
    nextRoutes: nextRoutes.length,
    nextApiRoutes: nextApiRoutes.length,
    honoRouteFiles: honoRouteFiles.length,
    envNames: envNames.length,
    duplicateMigrationNumbers,
    topicDocs: topicDirs.length,
    appAgents: appTargets.length,
    packageAgents: packageTargets.length,
  };
  writeFile("docs/architecture/repository-intelligence-report.json", JSON.stringify(report, null, 2));
}

