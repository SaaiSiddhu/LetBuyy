import {
  createReporter,
  readFile,
} from "./governance-common.mjs";

const reporter = createReporter("Repository intelligence validator");

const generator = readFile("scripts/generate-repository-intelligence.mjs");
const rootAgents = readFile("AGENTS.md");
const masterIntelligence = readFile("docs/architecture/master-system-intelligence.md");

reporter.assert(
  generator.includes('execFileSync("git", ["ls-files", "-z"]'),
  "repository intelligence generator must scan tracked files, not untracked local residue",
);

for (const expected of [
  'output: "apps/developer-portal/AGENTS.md"',
  'actual: "apps/developer-portal"',
  "Developer documentation, API reference, SDK quick-starts, and partner dashboard shell.",
]) {
  reporter.assert(generator.includes(expected), `repository intelligence generator missing developer portal target: ${expected}`);
}

for (const expected of [
  "<!-- GENERATED BY scripts/generate-repository-intelligence.mjs",
  "Developer Portal: `apps/developer-portal`",
  "`services/api-gateway` is the sole Commerce API backend",
  "`@letbuyy/shared-types` is the canonical cross-runtime domain contract",
  "apps/developer-portal`, `apps/theme-marketplace`",
  "Mobile runtimes: active `apps/mobile/merchant-app`; reserved/not-implemented mobile roots `apps/mobile/shopper-app` and `apps/mobile/operator-app`",
  "implemented `services/api-gateway`, `services/mobile-bff`, `services/webhook-service`, and `services/queue-workers`",
  "reserved/not-implemented service roots `services/checkout-runtime`, `services/search-service`, `services/media-service`, `services/notification-service`, `services/event-bus`, and `services/analytics-pipeline`",
  "Active replay chain: `000_baseline.sql` plus additive forward migrations `073_*.sql` through `089_*.sql`",
  "Baseline public tables detected: 233 `CREATE TABLE public.*` statements in `000_baseline.sql`",
  "Cloudflare agent setup authority lives at `https://developers.cloudflare.com/agent-setup/prompt.md`",
  "The `/api/seed` route in storefront-runtime is guarded by `NODE_ENV` and `SEED_SECRET`",
]) {
  reporter.assert(rootAgents.includes(expected), `root AGENTS generated output missing: ${expected}`);
}

for (const forbiddenLocalDraft of [
  "CODEX_FOUNDATION_HARDENING_MISSION_V2.md",
  "LETBUYY_CUSTOM_DOMAIN_V2.md",
  "LETBUYY_PRODUCTION_AUDIT_2026-06-06.md",
  "docs/mobile-migration-blueprint",
]) {
  reporter.assert(
    !rootAgents.includes(forbiddenLocalDraft) && !masterIntelligence.includes(forbiddenLocalDraft),
    `generated intelligence must not include untracked local draft: ${forbiddenLocalDraft}`,
  );
}

reporter.finish("generated AGENTS and master intelligence topology checked");
