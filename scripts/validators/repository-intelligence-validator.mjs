import {
  createReporter,
  readFile,
} from "./governance-common.mjs";

const reporter = createReporter("Repository intelligence validator");

const generator = readFile("scripts/generate-repository-intelligence.mjs");
const rootAgents = readFile("AGENTS.md");

reporter.assert(
  !rootAgents.startsWith("<!-- GENERATED BY scripts/generate-repository-intelligence.mjs"),
  "root AGENTS.md must be hand-authored AGENTS_V2, not generated repository intelligence",
);

for (const expected of [
  "# LETBUYY_AGENTS_V2",
  "HAND-AUTHORED LAW. NOT GENERATED.",
  "LETBUYY_CONSTITUTION.md",
  "one modular monolith",
  "The 8 canonical runtimes",
  "MUST NOT build (for this envelope):",
  "PAY-R3",
  "SEC-R6",
]) {
  reporter.assert(rootAgents.includes(expected), `root AGENTS.md missing AGENTS_V2 authority text: ${expected}`);
}

for (const rejected of [
  "Current source scan:",
  "After significant architecture changes, regenerate `docs/architecture/master-system-intelligence.md`",
  "Distributed Runtime: `packages/distributed-runtime`",
  "Projection Runtime: `packages/projection-runtime`",
  "Runtime Composition: `packages/runtime-composition`",
]) {
  reporter.assert(!rootAgents.includes(rejected), `root AGENTS.md still contains generated drift text: ${rejected}`);
}

reporter.assert(
  generator.includes("RETIRED_REPOSITORY_INTELLIGENCE_GENERATOR"),
  "repository intelligence generator must be explicitly retired so it cannot promote repo drift to law",
);

reporter.assert(
  !generator.includes("writeFile(\"AGENTS.md\"") && !generator.includes("writeFile('AGENTS.md'"),
  "repository intelligence generator must not write root AGENTS.md",
);

reporter.finish("AGENTS_V2 promotion and generator retirement checked");
