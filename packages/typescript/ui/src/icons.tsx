export type MaterialIconName = keyof typeof materialIconMap | (string & {});

export interface MaterialIconProps extends Omit<LucideProps, 'name'> {
    name: MaterialIconName;
    className?: string;
    style?: CSSProperties;
}

export function MaterialIcon({
    name,
    className = '',
    size,
    strokeWidth = 2,
    ...props
}: MaterialIconProps) {
    const Icon = materialIconMap[name as keyof typeof materialIconMap] ?? Circle;
    const normalizedClassName = className ? `letbuyy-icon ${className}` : 'letbuyy-icon';

    return (
        <Icon
            aria-hidden="true"
            focusable="false"
            width={size ?? '1em'}
            height={size ?? '1em'}
            strokeWidth={strokeWidth}
            className={normalizedClassName}
            {...props}
        />
    );
}
