function kebabCase(value: string) {
    return value.replace(/[A-Z]/g, (match) => `-${match.toLowerCase()}`).toLowerCase();
}

function appendTokenVariables(target: CssVariableMap, prefix: string[], tokens: unknown) {
    if (typeof tokens === 'string') {
        target[`--${prefix.join('-')}` as `--${string}`] = tokens;
        return;
    }

    if (typeof tokens !== 'object' || tokens === null) return;

    for (const [key, value] of Object.entries(tokens as Record<string, unknown>)) {
        appendTokenVariables(target, [...prefix, kebabCase(key)], value);
    }
}

