    required String commentId,
    required String reelId,
  }) async {
    try {
      // Check if already 3 pinned
      final pinnedSnapshot = await _commentsCollection
          .where('reelId', isEqualTo: reelId)
          .where('isPinned', isEqualTo: true)
          .get();
      
      if (pinnedSnapshot.docs.length >= 3) {
        print('⚠️ Maximum 3 pinned comments allowed');
        return false;
      }
      
      await _commentsCollection.doc(commentId).update({
        'isPinned': true,
      });
      
      print('✅ Comment pinned: $commentId');
      return true;
    } catch (e) {
      print('❌ Error pinning comment: $e');
      return false;
    }
  }
  
