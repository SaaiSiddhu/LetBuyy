  // SELLER PROFILE & FOLLOW
  // ============================================================
  
  CollectionReference<Map<String, dynamic>> get _followersCollection =>
      _firestore.collection('seller_followers');
  
  /// Follow a seller
  Future<bool> followSeller({
    required String sellerId,
    required String userId,
  }) async {
    try {
      await _followersCollection
          .doc(sellerId)
          .collection('followers')
          .doc(userId)
          .set({
        'followedAt': FieldValue.serverTimestamp(),
      });
      
      // Update follower count on seller
      await _firestore.collection('sellers').doc(sellerId).update({
        'followerCount': FieldValue.increment(1),
      });
      
      print('✅ Followed seller: $sellerId');
      return true;
    } catch (e) {
      print('❌ Error following seller: $e');
      return false;
    }
  }
  
  /// Unfollow a seller
  Future<bool> unfollowSeller({
    required String sellerId,
    required String userId,
  }) async {
    try {
      await _followersCollection
          .doc(sellerId)
          .collection('followers')
          .doc(userId)
          .delete();
      
      // Update follower count on seller
      await _firestore.collection('sellers').doc(sellerId).update({
        'followerCount': FieldValue.increment(-1),
      });
      
      print('✅ Unfollowed seller: $sellerId');
      return true;
    } catch (e) {
      print('❌ Error unfollowing seller: $e');
      return false;
    }
  }
  
  /// Check if user follows a seller
  Future<bool> isFollowing({
    required String sellerId,
    required String userId,
  }) async {
    try {
      final doc = await _followersCollection
          .doc(sellerId)
          .collection('followers')
          .doc(userId)
          .get();
      return doc.exists;
    } catch (e) {
      return false;
    }
  }
  
