  /// Create a new reel with video upload
  Future<ReelModel> createReel({
    required String sellerId,
    required String productId,
    required File videoFile,
    required String caption,
    required List<String> hashtags,
    required ProductModel product,
  }) async {
    try {
      // 1. Generate reel ID
      final docRef = _reelsCollection.doc();
      final reelId = docRef.id;
      
      // 2. Upload video to Firebase Storage
      final videoPath = 'reels/$sellerId/$reelId.mp4';
      final uploadTask = _storage.ref(videoPath).putFile(
        videoFile,
        SettableMetadata(contentType: 'video/mp4'),
      );
      
      final snapshot = await uploadTask;
      final videoUrl = await snapshot.ref.getDownloadURL();
      
      // 3. Create reel document
      final reel = ReelModel(
        id: reelId,
        sellerId: sellerId,
        productId: productId,
        videoUrl: videoUrl,
        thumbnailUrl: null, // Will be generated by Cloud Function
        duration: 0, // Will be updated after processing
        caption: caption,
        hashtags: hashtags,
        status: ReelStatus.pending, // Ready for admin moderation
        productName: product.name,
        productPrice: product.price,
        productSalePrice: product.salePrice,
        productImage: product.images.isNotEmpty ? product.images.first : '',
        createdAt: DateTime.now(),
      );
      
      await docRef.set(reel.toMap());
      
      // 4. Create empty stats document
      await _statsCollection.doc(reelId).set(
        ReelStatsModel.empty(reelId).toMap(),
      );
      
      print('✅ Reel created: $reelId');
      return reel;
    } catch (e) {
      print('❌ Error creating reel: $e');
      rethrow;
    }
  }
  
  /// Create a new reel from external link (Instagram/YouTube)
  /// No video download - stores the embed URL for playback
  Future<ReelModel> createReelFromLink({
    required String sellerId,
    required String productId,
    required String sourceType,    // 'instagram' or 'youtube'
    required String externalUrl,   // Original link from user
    required String caption,
    required List<String> hashtags,
    required ProductModel product,
  }) async {
    try {
      // 1. Generate reel ID
      final docRef = _reelsCollection.doc();
      final reelId = docRef.id;
      
      // 2. Convert URL to embeddable format
      String embedUrl = externalUrl;
      String? thumbnailUrl;
      
      if (sourceType == 'youtube') {
        // Extract video ID and create embed URL
        final videoId = _extractYouTubeVideoId(externalUrl);
        if (videoId != null) {
          embedUrl = 'https://www.youtube.com/embed/$videoId';
          thumbnailUrl = 'https://img.youtube.com/vi/$videoId/hqdefault.jpg';
        }
      } else if (sourceType == 'instagram') {
        // Instagram embeds need to be handled via webview
        // Store the original URL with /embed suffix
        if (!externalUrl.contains('/embed')) {
          embedUrl = externalUrl.replaceAll('/?', '/embed/?');
          if (!embedUrl.contains('/embed')) {
            embedUrl = '$externalUrl/embed/';
          }
        }
      }
      
      // 3. Create reel document with external source info
      final reel = ReelModel(
        id: reelId,
        sellerId: sellerId,
        productId: productId,
        videoUrl: embedUrl,           // Embeddable URL
        thumbnailUrl: thumbnailUrl ?? product.images.firstOrNull,
        duration: 0,
        caption: caption,
        hashtags: hashtags,
        status: ReelStatus.active,    // External links skip moderation
        productName: product.name,
        productPrice: product.price,
        productSalePrice: product.salePrice,
        productImage: product.images.isNotEmpty ? product.images.first : '',
        createdAt: DateTime.now(),
        sourceType: sourceType,       // Store source type
        externalUrl: externalUrl,     // Store original URL
      );
      
      await docRef.set(reel.toMap());
      
      // 4. Create empty stats document
      await _statsCollection.doc(reelId).set(
        ReelStatsModel.empty(reelId).toMap(),
      );
      
      print('✅ Reel created from $sourceType link: $reelId');
      return reel;
    } catch (e) {
      print('❌ Error creating reel from link: $e');
      rethrow;
    }
  }
  
  /// Extract YouTube video ID from various URL formats
  String? _extractYouTubeVideoId(String url) {
    // Handle: youtube.com/shorts/VIDEO_ID
    final shortsMatch = RegExp(r'youtube\.com/shorts/([a-zA-Z0-9_-]+)').firstMatch(url);
    if (shortsMatch != null) return shortsMatch.group(1);
    
    // Handle: youtu.be/VIDEO_ID
    final shortMatch = RegExp(r'youtu\.be/([a-zA-Z0-9_-]+)').firstMatch(url);
    if (shortMatch != null) return shortMatch.group(1);
    
    // Handle: youtube.com/watch?v=VIDEO_ID
    final watchMatch = RegExp(r'youtube\.com/watch\?v=([a-zA-Z0-9_-]+)').firstMatch(url);
    if (watchMatch != null) return watchMatch.group(1);
    
    return null;
  }

  
