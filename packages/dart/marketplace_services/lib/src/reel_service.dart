  /// Get total stats for seller's reels
  Future<Map<String, dynamic>> getSellerReelAnalytics(String sellerId) async {
    try {
      final reelsSnapshot = await _reelsCollection
          .where('sellerId', isEqualTo: sellerId)
          .get();
      
      int totalViews = 0;
      int totalLikes = 0;
      int totalAddToCart = 0;
      double totalRevenue = 0;
      
      for (final reelDoc in reelsSnapshot.docs) {
        final statsDoc = await _statsCollection.doc(reelDoc.id).get();
        if (statsDoc.exists) {
          final stats = ReelStatsModel.fromFirestore(statsDoc);
          totalViews += stats.views;
          totalLikes += stats.likes;
          totalAddToCart += stats.addToCartCount;
          totalRevenue += stats.revenue;
        }
      }
      
      return {
        'totalReels': reelsSnapshot.docs.length,
        'totalViews': totalViews,
        'totalLikes': totalLikes,
        'totalAddToCart': totalAddToCart,
        'totalRevenue': totalRevenue,
      };
    } catch (e) {
      print('❌ Error getting seller analytics: $e');
      return {};
    }
  }
  
