    required String reelId,
    required ReelStatus status,
    String? moderationNote,
  }) async {
    try {
      final updates = <String, dynamic>{
        'status': status.value,
        'updatedAt': FieldValue.serverTimestamp(),
      };
      
      if (status == ReelStatus.active) {
        updates['publishedAt'] = FieldValue.serverTimestamp();
      }
      
      if (moderationNote != null) {
        updates['moderationNote'] = moderationNote;
      }
      
      await _reelsCollection.doc(reelId).update(updates);
      print('✅ Reel status updated: $reelId → ${status.value}');
    } catch (e) {
      print('❌ Error updating reel status: $e');
      rethrow;
    }
  }
  
