  /// Get unanswered comments (no seller reply) for a seller's reels
  Stream<List<ReelCommentModel>> getUnansweredComments(String sellerId) {
    // First get seller's reels, then get unanswered comments
    return _reelsCollection
        .where('sellerId', isEqualTo: sellerId)
        .where('status', isEqualTo: 'active')
        .snapshots()
        .asyncMap((reelsSnapshot) async {
          final reelIds = reelsSnapshot.docs.map((d) => d.id).toList();
          if (reelIds.isEmpty) return <ReelCommentModel>[];
          
          // Get comments without seller replies
          final comments = <ReelCommentModel>[];
          for (final reelId in reelIds.take(10)) { // Limit for performance
            final snapshot = await _commentsCollection
                .where('reelId', isEqualTo: reelId)
                .where('parentCommentId', isNull: true)
                .where('isSellerReply', isEqualTo: false)
                .orderBy('createdAt', descending: true)
                .limit(20)
                .get();
            
            for (final doc in snapshot.docs) {
              final comment = ReelCommentModel.fromFirestore(doc);
              // Check if this comment has a seller reply
              final repliesSnapshot = await _commentsCollection
                  .where('parentCommentId', isEqualTo: doc.id)
                  .where('isSellerReply', isEqualTo: true)
                  .limit(1)
                  .get();
              
              if (repliesSnapshot.docs.isEmpty) {
                comments.add(comment);
              }
            }
          }
          return comments;
        });
  }
  
  /// Get comment statistics for a seller
  Future<Map<String, int>> getSellerCommentStats(String sellerId) async {
    try {
      // Get all seller's reel IDs
      final reelsSnapshot = await _reelsCollection
          .where('sellerId', isEqualTo: sellerId)
          .where('status', isEqualTo: 'active')
          .get();
      
      final reelIds = reelsSnapshot.docs.map((d) => d.id).toList();
      if (reelIds.isEmpty) {
        return {'total': 0, 'pinned': 0, 'unanswered': 0};
      }
      
      int totalComments = 0;
      int pinnedComments = 0;
      int unansweredComments = 0;
      
      for (final reelId in reelIds.take(20)) {
        final commentsSnapshot = await _commentsCollection
            .where('reelId', isEqualTo: reelId)
            .where('parentCommentId', isNull: true)
            .get();
        
        for (final doc in commentsSnapshot.docs) {
          totalComments++;
          final data = doc.data();
          if (data['isPinned'] == true) pinnedComments++;
          
          // Check if seller replied
          final repliesSnapshot = await _commentsCollection
              .where('parentCommentId', isEqualTo: doc.id)
              .where('isSellerReply', isEqualTo: true)
              .limit(1)
              .get();
          if (repliesSnapshot.docs.isEmpty) unansweredComments++;
        }
      }
      
      return {
        'total': totalComments,
        'pinned': pinnedComments,
        'unanswered': unansweredComments,
      };
    } catch (e) {
      print('❌ Error getting comment stats: $e');
      return {'total': 0, 'pinned': 0, 'unanswered': 0};
    }
  }
  
