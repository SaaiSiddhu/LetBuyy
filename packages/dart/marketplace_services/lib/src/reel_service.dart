  /// Toggle like on a reel
  Future<bool> toggleLike({
    required String reelId,
    required String userId,
  }) async {
    try {
      final likeId = '${reelId}_$userId';
      final likeDoc = await _likesCollection.doc(likeId).get();
      
      if (likeDoc.exists) {
        // Unlike
        await _likesCollection.doc(likeId).delete();
        await _statsCollection.doc(reelId).update({
          'likes': FieldValue.increment(-1),
        });
        return false;
      } else {
        // Like
        await _likesCollection.doc(likeId).set({
          'reelId': reelId,
          'userId': userId,
          'timestamp': FieldValue.serverTimestamp(),
        });
        await _statsCollection.doc(reelId).update({
          'likes': FieldValue.increment(1),
        });
        return true;
      }
    } catch (e) {
      print('❌ Error toggling like: $e');
      return false;
    }
  }
  
