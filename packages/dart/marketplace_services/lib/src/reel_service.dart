  /// Get all active reels for the feed (paginated)
  /// Falls back to createdAt if publishedAt index is missing
  Stream<List<ReelModel>> getReelsFeed({int limit = 10}) {
    print('🎬 getReelsFeed() called with limit=$limit');
    
    // Try with publishedAt first (requires Firestore index)
    return _reelsCollection
        .where('status', isEqualTo: 'active')
        .orderBy('createdAt', descending: true)  // Use createdAt (always exists)
        .limit(limit)
        .snapshots()
        .map((snapshot) {
          print('🎬 Firestore returned ${snapshot.docs.length} reels');
          if (snapshot.docs.isEmpty) {
            print('⚠️ No active reels found in Firestore');
          }
          return snapshot.docs
              .map((doc) => ReelModel.fromFirestore(doc))
              .toList();
        })
        .handleError((error) {
          print('❌ Reels feed error: $error');
          // Return empty stream on error
          return <ReelModel>[];
        });
  }
  
  /// Get paginated feed with cursor
  Future<List<ReelModel>> getReelsFeedPaginated({
    int limit = 10,
    DocumentSnapshot? startAfter,
  }) async {
    try {
      Query<Map<String, dynamic>> query = _reelsCollection
          .where('status', isEqualTo: 'active')
          .orderBy('createdAt', descending: true)  // Use createdAt (always exists)
          .limit(limit);
      
      if (startAfter != null) {
        query = query.startAfterDocument(startAfter);
      }
      
      final snapshot = await query.get();
      print('🎬 Paginated query returned ${snapshot.docs.length} reels');
      return snapshot.docs.map((doc) => ReelModel.fromFirestore(doc)).toList();
    } catch (e) {
      print('❌ Error getting reels feed: $e');
      return [];
    }
  }
  
